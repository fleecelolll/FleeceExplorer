__lensModules["panels/viewer3d"] = function()
-- 3D object viewer: renders a clone of the selected model in a ViewportFrame.

local UserInputService = game:GetService("UserInputService")

local Root = __lensRequire("ui/root")
local Theme = __lensRequire("core/theme")
local Toast = __lensRequire("ui/toast")
local UI = __lensRequire("ui/base")
local Util = __lensRequire("core/util")
local Widgets = __lensRequire("ui/widgets")
local Window = __lensRequire("ui/window")

local Viewer = {}

local TOOLBAR = 26

local window, viewport, worldModel, camera, statusLabel
local target = nil
local yaw, pitch, distance = math.rad(35), math.rad(-20), 20
local pivot = Vector3.zero
local autoRotate = true

--------------------------------------------------------------------------------
-- Cloning
--------------------------------------------------------------------------------

-- Archivable=false instances refuse to clone, so it is flipped for the duration
-- of the copy and restored afterwards.
local function cloneForPreview(instance)
    local touched = {}

    local function force(node)
        local ok, archivable = pcall(function()
            return node.Archivable
        end)
        if ok and archivable == false then
            pcall(function()
                node.Archivable = true
            end)
            touched[#touched + 1] = node
        end
    end

    force(instance)
    local ok, descendants = pcall(function()
        return instance:GetDescendants()
    end)
    if ok then
        for _, descendant in ipairs(descendants) do
            force(descendant)
        end
    end

    local cloneOk, clone = pcall(function()
        return instance:Clone()
    end)

    for _, node in ipairs(touched) do
        pcall(function()
            node.Archivable = false
        end)
    end

    if not cloneOk or not clone then
        return nil
    end

    -- Scripts in the preview would run against a WorldModel; strip them.
    for _, descendant in ipairs(clone:GetDescendants()) do
        local isScript = false
        pcall(function()
            isScript = descendant:IsA("LuaSourceContainer")
        end)
        if isScript then
            pcall(function()
                descendant:Destroy()
            end)
        end
    end

    return clone
end

local function boundsOf(instance)
    local ok, isModel = pcall(function()
        return instance:IsA("Model")
    end)

    if ok and isModel then
        local boundsOk, cframe, size = pcall(function()
            return instance:GetBoundingBox()
        end)
        if boundsOk then
            return cframe.Position, size
        end
    end

    local partOk, isPart = pcall(function()
        return instance:IsA("BasePart")
    end)
    if partOk and isPart then
        return instance.Position, instance.Size
    end

    return Vector3.zero, Vector3.one * 4
end

--------------------------------------------------------------------------------
-- Camera
--------------------------------------------------------------------------------

local function updateCamera()
    local offset = Vector3.new(
        math.cos(pitch) * math.sin(yaw),
        math.sin(pitch),
        math.cos(pitch) * math.cos(yaw)
    ) * distance

    camera.CFrame = CFrame.lookAt(pivot + offset, pivot)
end

