    if type(text) ~= "string" or text == "" then
        return nil
    end
    local ok, decoded = pcall(function()
        return HttpService:JSONDecode(text)
    end)
    if ok and type(decoded) == "table" then
        return decoded
    end
    return nil
end

function Config.load()
    local stored = decode(Env.readFile(FILE))
    if stored then
        state = Util.merge(Config.defaults, stored)
    end
    return state
end

local writeSoon = Util.debounced(0.75, function()
    local ok, encoded = pcall(function()
        return HttpService:JSONEncode(state)
    end)
    if ok then
        Env.writeFile(FILE, encoded)
    end
end)

function Config.save()
    writeSoon()
end

function Config.all()
    return state
end

-- Dotted access: Config.get("ui.rowHeight")
function Config.get(path, fallback)
    local node = state
    for segment in string.gmatch(path, "[^%.]+") do
        if type(node) ~= "table" then
            return fallback
        end
        node = node[segment]
    end
    if node == nil then
        return fallback
    end
    return node
end

function Config.set(path, value)
    local segments = {}
    for segment in string.gmatch(path, "[^%.]+") do
        segments[#segments + 1] = segment
    end
    if #segments == 0 then
        return
    end

    local node = state
    for index = 1, #segments - 1 do
        local key = segments[index]
        if type(node[key]) ~= "table" then
            node[key] = {}
        end
        node = node[key]
    end

    local leaf = segments[#segments]
    if node[leaf] == value then
        return
    end
    node[leaf] = value

    Config.save()
    Config.changed:fire(path, value)
end

function Config.reset()
    state = Util.deepCopy(Config.defaults)
    Config.save()
    Config.changed:fire("*", state)
end

return Config

end
