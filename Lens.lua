-- Bulk dumps
--------------------------------------------------------------------------------

function Serialize.attributes(instance)
    local ok, attributes = pcall(function()
        return instance:GetAttributes()
    end)
    if not ok or not attributes then
        return "-- no attributes"
    end

    local names = {}
    for name in pairs(attributes) do
        names[#names + 1] = name
    end
    table.sort(names)

    if #names == 0 then
        return "-- no attributes"
    end

    local lines = {}
    for _, name in ipairs(names) do
        lines[#lines + 1] = string.format(
            "instance:SetAttribute(%s, %s)",
            Util.quoteString(name), Serialize.toLua(attributes[name])
        )
    end
    return table.concat(lines, "\n")
end

function Serialize.properties(instance, options)
    options = options or {}
    local className = Util.safeClass(instance)
    local descriptors = ApiDump.propertiesFor(className)

    if #descriptors == 0 then
        return "-- API dump not loaded yet"
    end

    local lines = { string.format("-- %s (%s)", Util.safeName(instance), className) }

    for _, descriptor in ipairs(descriptors) do
        if not descriptor.deprecated and (options.includeHidden or not descriptor.hidden) then
            local ok, value = pcall(function()
                return instance[descriptor.name]
            end)
            if ok then
                local prefix = descriptor.readOnly and "-- " or ""
                lines[#lines + 1] = string.format(
                    "%sinstance.%s = %s",
                    prefix, descriptor.name, Serialize.toLua(value)
                )
            end
        end
    end

    return table.concat(lines, "\n")
end

function Serialize.everything(instance)
    local CollectionService = Env.service("CollectionService")
    local sections = {
        "-- Path: " .. Util.instancePath(instance),
        "",
        "-- Properties",
        Serialize.properties(instance),
        "",
        "-- Attributes",
        Serialize.attributes(instance),
    }

    local ok, tags = pcall(function()
        return CollectionService:GetTags(instance)
    end)
    sections[#sections + 1] = ""
    sections[#sections + 1] = "-- Tags"
    if ok and #tags > 0 then
        for _, tag in ipairs(tags) do
            sections[#sections + 1] = string.format(
                "CollectionService:AddTag(instance, %s)",
                Util.quoteString(tag)
            )
        end
    else
        sections[#sections + 1] = "-- none"
    end

    return table.concat(sections, "\n")
end

return Serialize

end
