        Motion.tween(row.marker, { Size = UDim2.new(0, markerWidth, 0.62, 0) }, Motion.BASE)
    end

    local colour
    if node.removed then
        colour = Theme.color("danger")
    elseif selected then
        colour = Theme.color("text")
    elseif node.depth == 0 then
        colour = Theme.color("text")
    else
        colour = Theme.color("textDim")
    end
    row.name.TextColor3 = colour
end

