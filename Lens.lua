function Window:persist()
    Config.set("panels." .. self.id, {
        x = math.floor(self.frame.Position.X.Offset),
        y = math.floor(self.frame.Position.Y.Offset),
        width = math.floor(self.frame.Size.X.Offset),
        height = math.floor(self.frame.Size.Y.Offset),
        visible = self.frame.Visible,
    })
end

function Window:setupDrag()
    local dragging = false
    local dragStart, startPosition

    self.titleBar.InputBegan:Connect(function(input)
        if input.UserInputType ~= Enum.UserInputType.MouseButton1 and input.UserInputType ~= Enum.UserInputType.Touch then
            return
        end
        dragging = true
        dragStart = input.Position
        startPosition = self.frame.Position
        self:bringToFront()
    end)

    UserInputService.InputChanged:Connect(function(input)
        if not dragging then
            return
        end
        if input.UserInputType ~= Enum.UserInputType.MouseMovement and input.UserInputType ~= Enum.UserInputType.Touch then
            return
        end

        local delta = input.Position - dragStart
        local viewport = Root.gui.AbsoluteSize
        local size = self.frame.AbsoluteSize

        -- Keep at least a slice of the title bar reachable.
        local newX = Util.clamp(startPosition.X.Offset + delta.X, -size.X + 60, viewport.X - 60)
        local newY = Util.clamp(startPosition.Y.Offset + delta.Y, 0, viewport.Y - TITLE_HEIGHT)
        self.frame.Position = UDim2.fromOffset(newX, newY)
    end)

    UserInputService.InputEnded:Connect(function(input)
        if not dragging then
            return
        end
        if input.UserInputType == Enum.UserInputType.MouseButton1 or input.UserInputType == Enum.UserInputType.Touch then
            dragging = false
            self:persist()
        end
    end)
end

