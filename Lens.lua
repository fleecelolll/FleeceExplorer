local function highlightColor()
    local stored = Config.get("explorer.highlightColor", { 0.2, 0.75, 1 })
    if type(stored) == "table" and #stored >= 3 then
        return Color3.new(stored[1], stored[2], stored[3])
    end
    return Theme.color("accent")
end

-- Roblox degrades Highlight quality past roughly two dozen simultaneous
-- instances, so the count is capped and the rest go un-adorned.
local function refreshAdornments()
    clearAdornments()

    if not Config.get("explorer.highlightSelection", true) then
        return
    end

    local limit = Config.get("explorer.maxHighlights", 16)
    local color = highlightColor()
    local folder = ensureFolder()
    local guiTargets = {}
    local used = 0

    for _, instance in ipairs(ordered) do
        if used >= limit then
            break
        end

        local ok, isWorld = pcall(function()
            return instance:IsA("BasePart") or instance:IsA("Model")
        end)

        if ok and isWorld then
            local highlight = Instance.new("Highlight")
            highlight.FillColor = color
            highlight.OutlineColor = color
            highlight.FillTransparency = 0.65
            highlight.OutlineTransparency = 0
            highlight.DepthMode = Enum.HighlightDepthMode.AlwaysOnTop
            highlight.Adornee = instance
            highlight.Parent = folder
            highlights[#highlights + 1] = highlight
            used = used + 1
        else
            local guiOk, isGui = pcall(function()
                return instance:IsA("GuiObject")
            end)
            if guiOk and isGui then
                guiTargets[#guiTargets + 1] = instance
                used = used + 1
            end
        end
    end

    if #guiTargets == 0 then
        return
    end

    -- GuiObjects cannot be Adornees, so they get an outline frame that tracks
    -- their absolute rect each frame instead.
    for _, target in ipairs(guiTargets) do
        local box = UI.frame({
            Name = "GuiOutline",
            BackgroundTransparency = 1,
            Visible = false,
            ZIndex = 890,
            Parent = Root.tooltip,
        })
        local stroke = Instance.new("UIStroke")
        stroke.Color = color
        stroke.Thickness = 2
        stroke.Parent = box
        -- guiBoxes stays index-aligned with guiTargets; the render loop pairs them.
        guiBoxes[#guiBoxes + 1] = box
    end

    renderConnection = RunService.RenderStepped:Connect(function()
        for index, target in ipairs(guiTargets) do
            local box = guiBoxes[index]
            if not box then
                break
            end

            local ok, position, size = pcall(function()
                return target.AbsolutePosition, target.AbsoluteSize
            end)

            if ok and size and size.X > 0 and size.Y > 0 then
                box.Position = UDim2.fromOffset(position.X, position.Y)
                box.Size = UDim2.fromOffset(size.X, size.Y)
                box.Visible = true
            else
                box.Visible = false
            end
        end
    end)
end

--------------------------------------------------------------------------------
-- Mutation
--------------------------------------------------------------------------------

local function commit()
    refreshAdornments()
    Selection.changed:fire(ordered)
end

function Selection.clear(silent)
    if #ordered == 0 then
        return
    end
    table.clear(ordered)
    table.clear(lookup)
    anchorIndex = nil
    if not silent then
        commit()
    end
end

function Selection.set(instance)
    Selection.clear(true)
    if instance then
        ordered[1] = instance
        lookup[instance] = true
        anchorIndex = Tree.indexOf(instance)
    end
    commit()
end

function Selection.setMany(instances)
    Selection.clear(true)
    for _, instance in ipairs(instances) do
        if not lookup[instance] then
            lookup[instance] = true
            ordered[#ordered + 1] = instance
        end
    end
    commit()
end

function Selection.add(instance, silent)
    if lookup[instance] then
        return
    end
    lookup[instance] = true
    ordered[#ordered + 1] = instance
    if not silent then
        commit()
    end
end

function Selection.remove(instance, silent)
    if not lookup[instance] then
        return
    end
    lookup[instance] = nil
    for index, candidate in ipairs(ordered) do
        if candidate == instance then
            table.remove(ordered, index)
            break
        end
    end
    if not silent then
        commit()
    end
end

function Selection.toggle(instance)
    if lookup[instance] then
        Selection.remove(instance)
    else
        Selection.add(instance)
        anchorIndex = Tree.indexOf(instance)
    end
end

-- Ctrl+Click toggles, Shift+Click extends from the anchor, plain click replaces.
function Selection.handleClick(instance, modifiers)
    if modifiers.ctrl then
        Selection.toggle(instance)
        return
    end

    if modifiers.shift and anchorIndex then
        local targetIndex = Tree.indexOf(instance)
        if targetIndex then
            local from = math.min(anchorIndex, targetIndex)
            local to = math.max(anchorIndex, targetIndex)
            Selection.clear(true)
            for index = from, to do
                local node = Tree.flat[index]
                if node and node.instance then
                    Selection.add(node.instance, true)
                end
            end
            commit()
            return
        end
    end

    Selection.set(instance)
end

-- One level of children per call, so repeated use walks down the tree.
function Selection.selectChildren()
    if #ordered == 0 then
        return 0
    end

    local next = {}
    local seen = {}
    for _, instance in ipairs(ordered) do
        for _, child in ipairs(Tree.childrenOf(instance)) do
            if not seen[child] then
                seen[child] = true
                next[#next + 1] = child
            end
        end
    end

    if #next == 0 then
        return 0
    end

    Selection.setMany(next)
    return #next
end

function Selection.selectParents()
    local next = {}
    local seen = {}
    for _, instance in ipairs(ordered) do
        local ok, parent = pcall(function()
            return instance.Parent
        end)
        if ok and parent and parent ~= game and not seen[parent] then
            seen[parent] = true
            next[#next + 1] = parent
        end
    end
    if #next == 0 then
        return 0
    end
    Selection.setMany(next)
    return #next
end

function Selection.refreshAdornments()
    refreshAdornments()
end

return Selection

end
