local rawFiltergc = filtergc
local rawGetloadedmodules = getloadedmodules
local rawGetscripts = getscripts
local rawSetfpscap = setfpscap

Env.has = {}

local function capability(name, value)
    Env.has[name] = type(value) == "function"
    return value
end

capability("gethui", rawGethui)
capability("cloneref", rawCloneref)
capability("getnilinstances", rawGetnilinstances)
capability("getinstances", rawGetinstances)
capability("decompile", rawDecompile)
