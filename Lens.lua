-- `instant` skips the tween, used when a pooled row is rebound to new data and
-- should not animate from the previous item's state.
function Explorer.paintRow(row, instant)
    local node = row.node
    if not node then
        return
    end

    local selected = node.instance ~= nil and Selection.contains(node.instance)

    local background, transparency
    if selected then
        background, transparency = Theme.color("selection"), 0
    elseif row.hovered then
        background, transparency = Theme.color("bg2"), 0
    else
        background, transparency = Theme.color("bg2"), 1
    end

    row.frame.BackgroundColor3 = background

    local markerWidth = selected and 2 or 0
    if instant then
