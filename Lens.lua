                Size = UDim2.new(1, 0, 0, rowHeight),
                LayoutOrder = index,
                BackgroundTransparency = 1,
                Text = "",
                AutoButtonColor = false,
                ZIndex = 603,
                Parent = scroll,
            })

            local text = UI.label({
                Size = UDim2.new(1, -20, 1, 0),
                Position = UDim2.fromOffset(10, 0),
                Text = entry.text or "",
                TextSize = 13,
                ZIndex = 604,
                Parent = item,
            })

            local hint
            if entry.hint then
                hint = UI.label({
                    Size = UDim2.new(0, 60, 1, 0),
                    Position = UDim2.new(1, -66, 0, 0),
                    Text = entry.hint,
                    TextSize = 11,
                    TextXAlignment = Enum.TextXAlignment.Right,
                    ZIndex = 604,
                    Parent = item,
                    theme = { TextColor3 = "textFaint" },
                })
            end

            local function paint(hover)
                if entry.disabled then
                    text.TextColor3 = Theme.color("textFaint")
                    item.BackgroundTransparency = 1
                    return
                end
                text.TextColor3 = entry.danger and Theme.color("danger") or Theme.color("text")
                item.BackgroundColor3 = Theme.color("bg3")
                item.BackgroundTransparency = hover and 0 or 1
            end
            paint(false)

            item.MouseEnter:Connect(function()
                paint(true)
            end)
            item.MouseLeave:Connect(function()
                paint(false)
            end)
            item.MouseButton1Click:Connect(function()
                if entry.disabled then
                    return
                end
                if not entry.keepOpen then
                    Widgets.closePopup()
                end
                if entry.onClick then
                    task.spawn(entry.onClick)
                end
            end)
        end
    end

    return blocker
end

