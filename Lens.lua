-- variant: "default" | "accent" | "ghost" | "danger"
function Widgets.button(props)
    local variant = props.variant or "default"

    local button = UI.new("TextButton", {
        Size = props.Size or UDim2.new(0, 90, 0, 24),
        Position = props.Position,
        AnchorPoint = props.AnchorPoint,
        LayoutOrder = props.LayoutOrder,
        Text = props.Text or "",
        Font = props.Font or UI.FONT_MEDIUM,
        TextSize = props.TextSize or 13,
        AutoButtonColor = false,
        BorderSizePixel = 0,
        ZIndex = props.ZIndex or 1,
        Parent = props.Parent,
    })

    if variant ~= "ghost" then
        UI.corner(button, props.radius or 7)
    end

    local hover, pressed, active = false, false, props.active == true

    local function paint()
        local background, text

        if variant == "accent" or active then
            background = Theme.color("accent")
            text = Theme.color("accentText")
        elseif variant == "danger" then
            background = Theme.color("danger")
            text = Theme.color("accentText")
        elseif variant == "ghost" then
            background = Theme.color("bg2")
            text = hover and Theme.color("text") or Theme.color("textDim")
        else
            background = Theme.color("bg2")
            text = Theme.color("text")
        end

        if pressed then
            background = lighten(background, -0.05)
        elseif hover then
            background = lighten(background, 0.06)
        end

        local transparency = (variant == "ghost" and not hover and not active) and 1 or 0
        -- Ghost buttons only grow a background once you interact with them.
        Motion.tween(button, {
            BackgroundColor3 = background,
            TextColor3 = text,
            BackgroundTransparency = transparency,
        }, Motion.FAST)
    end

    UI.repaint(button, paint)

    button.MouseEnter:Connect(function()
        hover = true
        paint()
    end)
    button.MouseLeave:Connect(function()
        hover = false
        pressed = false
        paint()
    end)
    button.MouseButton1Down:Connect(function()
        pressed = true
        paint()
    end)
    button.MouseButton1Up:Connect(function()
        pressed = false
        paint()
    end)

    if props.onClick then
        button.MouseButton1Click:Connect(function()
            props.onClick(button)
        end)
    end

    local api = {
        instance = button,
        setActive = function(value)
            if active == value then
                return
            end
            active = value == true
            paint()
        end,
        isActive = function()
            return active
        end,
        setText = function(text)
            button.Text = text
        end,
    }

    return button, api
end

