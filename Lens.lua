-- Normalises the several request() shapes executors ship into
-- { ok, status, body, err }.
function Env.httpRequest(options)
    if type(rawRequest) ~= "function" then
        local ok, body = pcall(function()
            return game:HttpGet(options.Url)
        end)
        if ok then
            return { ok = true, status = 200, body = body }
        end
        return { ok = false, status = 0, body = "", err = "no request function" }
    end

    local ok, response = pcall(rawRequest, options)
    if not ok then
        return { ok = false, status = 0, body = "", err = tostring(response) }
    end
    if type(response) ~= "table" then
        return { ok = false, status = 0, body = "", err = "malformed response" }
    end

    local status = response.StatusCode or response.status_code or 0
    local body = response.Body or response.body or ""
    return {
        ok = status >= 200 and status < 300,
        status = status,
        body = body,
        err = (status >= 200 and status < 300) and nil or ("HTTP " .. tostring(status)),
    }
end

