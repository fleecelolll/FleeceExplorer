    -- Saturation/brightness square.
    local square = UI.frame({
        Size = UDim2.fromOffset(186, 130),
        Position = UDim2.fromOffset(12, 12),
        BackgroundColor3 = Color3.fromHSV(hue, 1, 1),
        ZIndex = 602,
        Parent = panel,
    })
    UI.corner(square, 4)

    UI.new("UIGradient", {
        Color = ColorSequence.new(Color3.new(1, 1, 1), Color3.new(1, 1, 1)),
        Transparency = NumberSequence.new({
            NumberSequenceKeypoint.new(0, 0),
            NumberSequenceKeypoint.new(1, 1),
        }),
        Parent = square,
    })

    local darkness = UI.frame({
        Size = UDim2.fromScale(1, 1),
        BackgroundColor3 = Color3.new(0, 0, 0),
        BackgroundTransparency = 0,
        ZIndex = 603,
        Parent = square,
    })
    UI.corner(darkness, 4)
    UI.new("UIGradient", {
        Rotation = 90,
        Transparency = NumberSequence.new({
            NumberSequenceKeypoint.new(0, 1),
            NumberSequenceKeypoint.new(1, 0),
        }),
        Parent = darkness,
    })

    local cursor = UI.frame({
        Size = UDim2.fromOffset(9, 9),
        AnchorPoint = Vector2.new(0.5, 0.5),
        BackgroundColor3 = Color3.new(1, 1, 1),
        ZIndex = 605,
        Parent = square,
    })
    UI.corner(cursor, 5)
    UI.stroke(cursor, Color3.new(0, 0, 0), 1)

    -- Hue strip.
    local hueBar = UI.frame({
        Size = UDim2.fromOffset(186, 14),
        Position = UDim2.fromOffset(12, 150),
        BackgroundColor3 = Color3.new(1, 1, 1),
        ZIndex = 602,
        Parent = panel,
    })
    UI.corner(hueBar, 4)

    local hueKeypoints = {}
    for index = 0, 6 do
        hueKeypoints[#hueKeypoints + 1] = ColorSequenceKeypoint.new(index / 6, Color3.fromHSV(index / 6, 1, 1))
    end
    UI.new("UIGradient", {
        Color = ColorSequence.new(hueKeypoints),
        Parent = hueBar,
    })

    local hueCursor = UI.frame({
        Size = UDim2.fromOffset(4, 18),
        AnchorPoint = Vector2.new(0.5, 0.5),
        Position = UDim2.new(hue, 0, 0.5, 0),
        BackgroundColor3 = Color3.new(1, 1, 1),
        ZIndex = 604,
        Parent = hueBar,
    })
    UI.corner(hueCursor, 2)
    UI.stroke(hueCursor, Color3.new(0, 0, 0), 1)

    local preview = UI.frame({
        Size = UDim2.fromOffset(28, 28),
        Position = UDim2.fromOffset(12, 174),
        BackgroundColor3 = startColor,
        ZIndex = 602,
        Parent = panel,
    })
    UI.corner(preview, 4)
    UI.stroke(preview, "border", 1)

    local hexBox = Widgets.textbox({
        Size = UDim2.fromOffset(150, 28),
        Position = UDim2.fromOffset(48, 174),
        Text = string.format("#%02X%02X%02X", startColor.R * 255, startColor.G * 255, startColor.B * 255),
        ZIndex = 602,
        Parent = panel,
    })

    local function emit()
        local color = Color3.fromHSV(hue, saturation, brightness)
        preview.BackgroundColor3 = color
        square.BackgroundColor3 = Color3.fromHSV(hue, 1, 1)
        cursor.Position = UDim2.fromScale(saturation, 1 - brightness)
        hueCursor.Position = UDim2.new(hue, 0, 0.5, 0)
        hexBox.Text = string.format("#%02X%02X%02X", color.R * 255 + 0.5, color.G * 255 + 0.5, color.B * 255 + 0.5)
        if onChanged then
            onChanged(color)
        end
    end
    cursor.Position = UDim2.fromScale(saturation, 1 - brightness)

    local squareHit = UI.new("TextButton", {
        Size = UDim2.fromScale(1, 1),
        BackgroundTransparency = 1,
        Text = "",
        AutoButtonColor = false,
        ZIndex = 606,
        Parent = square,
    })
    local hueHit = UI.new("TextButton", {
        Size = UDim2.fromScale(1, 1),
        BackgroundTransparency = 1,
        Text = "",
        AutoButtonColor = false,
        ZIndex = 606,
        Parent = hueBar,
    })

    local draggingSquare, draggingHue = false, false

    local function updateSquare(inputPosition)
        saturation = Util.clamp((inputPosition.X - square.AbsolutePosition.X) / math.max(square.AbsoluteSize.X, 1), 0, 1)
        brightness = 1 - Util.clamp((inputPosition.Y - square.AbsolutePosition.Y) / math.max(square.AbsoluteSize.Y, 1), 0, 1)
        emit()
    end

    local function updateHue(inputPosition)
        hue = Util.clamp((inputPosition.X - hueBar.AbsolutePosition.X) / math.max(hueBar.AbsoluteSize.X, 1), 0, 1)
        emit()
    end

    squareHit.InputBegan:Connect(function(input)
        if input.UserInputType == Enum.UserInputType.MouseButton1 then
            draggingSquare = true
            updateSquare(input.Position)
        end
    end)
    hueHit.InputBegan:Connect(function(input)
        if input.UserInputType == Enum.UserInputType.MouseButton1 then
            draggingHue = true
            updateHue(input.Position)
        end
    end)
    UserInputService.InputChanged:Connect(function(input)
        if input.UserInputType ~= Enum.UserInputType.MouseMovement then
            return
        end
        if draggingSquare then
            updateSquare(input.Position)
        elseif draggingHue then
            updateHue(input.Position)
        end
    end)
    UserInputService.InputEnded:Connect(function(input)
        if input.UserInputType == Enum.UserInputType.MouseButton1 then
            draggingSquare = false
            draggingHue = false
        end
    end)

    hexBox.FocusLost:Connect(function()
        local hex = string.match(hexBox.Text, "#?(%x%x%x%x%x%x)")
        if not hex then
            return
        end
        local r = tonumber(string.sub(hex, 1, 2), 16) / 255
        local g = tonumber(string.sub(hex, 3, 4), 16) / 255
        local b = tonumber(string.sub(hex, 5, 6), 16) / 255
        hue, saturation, brightness = Color3.toHSV(Color3.new(r, g, b))
        emit()
    end)

    return blocker
end

return Widgets

end
__lensModules["ui/window"] = function()
-- Draggable, resizable panel window. Geometry persists per window id.

local UserInputService = game:GetService("UserInputService")

local Config = __lensRequire("core/config")
local Root = __lensRequire("ui/root")
local Theme = __lensRequire("core/theme")
local UI = __lensRequire("ui/base")
local Util = __lensRequire("core/util")

local Window = {}
Window.__index = Window

local topZIndex = 10
local openWindows = {}

local TITLE_HEIGHT = 28
local GRIP = 12

function Window.new(options)
    local self = setmetatable({}, Window)

    self.id = options.id
    self.minSize = options.minSize or Vector2.new(220, 160)
    self.visibleChanged = Util.Signal.new()

    local stored = Config.get("panels." .. self.id, {})
    local width = stored.width or options.width or 320
    local height = stored.height or options.height or 420
    local x = stored.x or options.x or 40
    local y = stored.y or options.y or 60
    local visible = stored.visible
    if visible == nil then
        visible = options.visible ~= false
    end

    -- Defaults are laid out for a roughly 1280x720 viewport; on anything
    -- smaller, shrink and pull the window back on screen rather than letting it
    -- open off the edge.
    local viewport = Root.gui and Root.gui.AbsoluteSize or Vector2.new(1280, 720)
    if viewport.X > 0 and viewport.Y > 0 then
        width = math.min(width, math.max(self.minSize.X, viewport.X - 16))
        height = math.min(height, math.max(self.minSize.Y, viewport.Y - 80))
        x = Util.clamp(x, 4, math.max(4, viewport.X - width - 4))
        y = Util.clamp(y, 4, math.max(4, viewport.Y - height - 4))
    end

    topZIndex = topZIndex + 1

    self.frame = UI.frame({
        Name = options.title or self.id,
        Size = UDim2.fromOffset(width, height),
        Position = UDim2.fromOffset(x, y),
        ZIndex = topZIndex,
        Visible = visible,
        ClipsDescendants = false,
        Parent = options.parent or Root.main,
        theme = { BackgroundColor3 = "bg0", BackgroundTransparency = "trans:window" },
    })
    UI.corner(self.frame, 10)
    UI.stroke(self.frame, "border", 1)

    -- Title bar
    self.titleBar = UI.frame({
        Size = UDim2.new(1, 0, 0, TITLE_HEIGHT),
        ZIndex = topZIndex + 1,
        Parent = self.frame,
        theme = { BackgroundColor3 = "bg1" },
    })
    UI.corner(self.titleBar, 10)

    -- Squares off the bottom corners of the rounded title bar.
    UI.frame({
        Size = UDim2.new(1, 0, 0, 8),
        Position = UDim2.new(0, 0, 1, -8),
        ZIndex = topZIndex + 1,
        Parent = self.titleBar,
        theme = { BackgroundColor3 = "bg1" },
    })

    self.titleLabel = UI.label({
        Size = UDim2.new(1, -70, 1, 0),
        Position = UDim2.fromOffset(10, 0),
        Text = options.title or self.id,
        Font = UI.FONT_MEDIUM,
        TextSize = 13,
        ZIndex = topZIndex + 2,
        Parent = self.titleBar,
    })

    self.headerRight = UI.frame({
        Size = UDim2.new(0, 60, 1, 0),
        Position = UDim2.new(1, -64, 0, 0),
        BackgroundTransparency = 1,
        ZIndex = topZIndex + 2,
        Parent = self.titleBar,
    })
    UI.list(self.headerRight, Enum.FillDirection.Horizontal, 2, Enum.VerticalAlignment.Center).HorizontalAlignment =
        Enum.HorizontalAlignment.Right

    if options.closable ~= false then
        local close = UI.new("TextButton", {
            Size = UDim2.fromOffset(20, 20),
            Text = "✕",
            Font = UI.FONT_MEDIUM,
            TextSize = 12,
            BackgroundTransparency = 1,
            AutoButtonColor = false,
            LayoutOrder = 100,
            ZIndex = topZIndex + 3,
            Parent = self.headerRight,
        })
        UI.corner(close, 4)

        local function paintClose(hover)
            close.TextColor3 = hover and Theme.color("accentText") or Theme.color("textDim")
            close.BackgroundColor3 = Theme.color("danger")
            close.BackgroundTransparency = hover and 0 or 1
        end
        UI.repaint(close, function()
            paintClose(false)
        end)
        close.MouseEnter:Connect(function()
            paintClose(true)
        end)
        close.MouseLeave:Connect(function()
            paintClose(false)
        end)
        close.MouseButton1Click:Connect(function()
            self:setVisible(false)
        end)
    end

    -- Content
    self.content = UI.frame({
        Size = UDim2.new(1, 0, 1, -TITLE_HEIGHT),
        Position = UDim2.fromOffset(0, TITLE_HEIGHT),
        BackgroundTransparency = 1,
        ClipsDescendants = true,
        ZIndex = topZIndex + 1,
        Parent = self.frame,
    })

    self:setupDrag()
    if options.resizable ~= false then
        self:setupResize()
    end

