-- Slides the rail off the right edge rather than snapping it off.
function Dock.setVisible(visible)
    if not rail or rail.Visible == visible then
        return
    end

    local width = rail.Size.X.Offset
    local shown = UDim2.new(1, -width - 8, 0, 8)
    local hidden = UDim2.new(1, 10, 0, 8)

    if visible then
        rail.Position = hidden
        rail.Visible = true
        Motion.tween(rail, { Position = shown }, Motion.SLOW)
    else
        local tween = Motion.tween(rail, { Position = hidden }, Motion.BASE)
        if tween then
            tween.Completed:Once(function()
                rail.Visible = false
                -- Restore the resting position so the next show starts clean.
                rail.Position = shown
            end)
        else
            rail.Visible = false
        end
    end

    -- persist() reads rail.Visible, which is still true mid-hide.
    persist(visible)
    Dock.visibleChanged:fire(visible)
end

function Dock.isVisible()
    return rail ~= nil and rail.Visible
end

function Dock.toggle()
    Dock.setVisible(not Dock.isVisible())
    return Dock.isVisible()
end

function Dock.setPropertiesVisible(visible)
    propertiesOpen = visible == true
    layout()
    persist()
end

function Dock.propertiesVisible()
    return propertiesOpen
end

function Dock.togglePropertiesPane()
    Dock.setPropertiesVisible(not propertiesOpen)
    return propertiesOpen
end

-- Panels used to own a Window; give them the same surface so callers that say
-- `Explorer.window:setVisible(true)` keep working against the dock.
function Dock.paneHandle(kind)
    return {
        setVisible = function(_, value)
            if kind == "properties" then
                Dock.setPropertiesVisible(value)
                if value then
                    Dock.setVisible(true)
                end
            else
                Dock.setVisible(value)
            end
        end,
        isVisible = function()
            if kind == "properties" then
                return Dock.isVisible() and propertiesOpen
            end
            return Dock.isVisible()
        end,
        toggle = function(self)
            local target = not self:isVisible()
            self:setVisible(target)
            return target
        end,
        setTitle = function() end,
        addHeaderButton = function(_, text, _, onClick)
            return Dock.headerButton(text, onClick)
        end,
    }
end

return Dock

