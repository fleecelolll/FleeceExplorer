-- Instances whose Parent is nil (or whose ancestry does not reach `game`).
-- getnilinstances is exact and cheap; the getgc sweep is the slow fallback.
function Env.getNilInstances()
    if type(rawGetnilinstances) == "function" then
        local ok, list = pcall(rawGetnilinstances)
        if ok and type(list) == "table" then
            return list, "getnilinstances"
        end
    end

    if type(rawGetinstances) == "function" then
        local ok, list = pcall(rawGetinstances)
        if ok and type(list) == "table" then
            local result = {}
            for _, instance in ipairs(list) do
                local safe, detached = pcall(function()
                    return not instance:IsDescendantOf(game)
                end)
                if safe and detached and instance ~= game then
                    result[#result + 1] = instance
                end
            end
            return result, "getinstances"
        end
    end

    if type(rawGetgc) == "function" then
        local ok, objects = pcall(rawGetgc, true)
        if ok and type(objects) == "table" then
            local result = {}
            local seen = {}
            for _, value in pairs(objects) do
                if typeof(value) == "Instance" and not seen[value] then
                    seen[value] = true
                    local safe, detached = pcall(function()
                        return not value:IsDescendantOf(game)
                    end)
                    if safe and detached and value ~= game then
                        result[#result + 1] = value
                    end
                end
            end
            return result, "getgc"
        end
    end

    return {}, "unavailable"
end

function Env.decompileScript(scriptInstance)
    if type(rawDecompile) ~= "function" then
        return nil, "decompile unavailable"
    end
    local ok, source = pcall(rawDecompile, scriptInstance)
    if not ok then
        return nil, tostring(source)
    end
    if type(source) ~= "string" or source == "" then
        return nil, "decompiler returned no source"
    end
    return source
end

function Env.scriptBytecode(scriptInstance)
    if type(rawGetscriptbytecode) ~= "function" then
        return nil, "getscriptbytecode unavailable"
    end
    local ok, bytecode = pcall(rawGetscriptbytecode, scriptInstance)
    if not ok or type(bytecode) ~= "string" or bytecode == "" then
        return nil, "could not read bytecode"
    end
    return bytecode
end

return Env

end
__lensModules["core/icons"] = function()
-- Studio class icons.
--
-- The client ships the icon strip at rbxasset://textures/ClassImages.png, but
-- nothing in a live client tells you which tile belongs to which class -
-- StudioService:GetClassIcon is Studio-only. The mapping instead comes from
-- ReflectionMetadata.xml's ExplorerImageIndex, which is exactly what Studio
-- itself keys off, so the icons are correct rather than guessed.
--
-- Tile geometry is measured, not assumed. The sheet is one row of square tiles,
-- so the tile size is simply the sheet's height, and ContentImageSize reports
-- it once the image has loaded. On the current sheet that is 1024/147 ~ 6.966
-- px per tile - deliberately not a round number, which is why sampling on an
-- 8px grid looks fine for the first few classes and then drifts badly (Folder,
-- index 77, lands ~80px out and renders as two icon halves).

local ApiDump = __lensRequire("core/apidump")
local Env = __lensRequire("core/env")
local Util = __lensRequire("core/util")

local Icons = {}

Icons.SHEET = "rbxasset://textures/ClassImages.png"

-- Fallback for the current sheet, replaced by the measured value at startup.
Icons.TILE = 1024 / 147
Icons.tileMeasured = false

Icons.ready = false
Icons.readyChanged = Util.Signal.new()

local METADATA_URL =
    "https://raw.githubusercontent.com/MaximumADHD/Roblox-Client-Tracker/roblox/ReflectionMetadata.xml"
local CACHE_FILE = "class-icons.json"

local indexByClass = {}
local resolved = {}

local FALLBACK_INDEX = 0

--------------------------------------------------------------------------------
-- Parsing
--------------------------------------------------------------------------------

local function parse(xml)
    local map = {}
    local pos = 1
    local marker = '<Item class="ReflectionMetadataClass">'

    while true do
        local start = string.find(xml, marker, pos, true)
        if not start then
            break
        end
        local finish = string.find(xml, marker, start + #marker, true) or #xml
        local chunk = string.sub(xml, start, finish)

        local name = string.match(chunk, '<string name="Name">(.-)</string>')
        -- ExplorerImageIndex is serialised as a string, not an int.
        local index = string.match(chunk, '<string name="ExplorerImageIndex">(%-?%d+)</string>')
        if name and index then
            map[name] = tonumber(index)
        end

        pos = finish
    end

    return map
end

local function ingest(map)
    indexByClass = map
    resolved = {}
    Icons.ready = true
    Icons.readyChanged:fire(true)
end

-- The sheet is a single row, so tile size == sheet height. Measuring beats
-- hardcoding: if Roblox reflows the sheet, the icons follow.
function Icons.measureTile()
    task.spawn(function()
        local Root = __lensRequire("ui/root")
        -- An invisible ImageLabel never loads, so IsLoaded would never flip.
        -- Keep it renderable but 1px and parked off-screen.
        local holder = Instance.new("ImageLabel")
        holder.Image = Icons.SHEET
        holder.Size = UDim2.fromOffset(1, 1)
        holder.Position = UDim2.fromOffset(0, 0)
        holder.BackgroundTransparency = 1
        holder.Visible = true
        holder.Parent = Root.gui or game:GetService("CoreGui")

        local deadline = os.clock() + 5
        repeat
            task.wait(0.1)
        until holder.IsLoaded or os.clock() > deadline

        local size = holder.ContentImageSize
        holder:Destroy()

        if size and size.Y > 0.5 then
            Icons.TILE = size.Y
            Icons.tileMeasured = true
            Icons.readyChanged:fire(Icons.ready)
        end
    end)
end

function Icons.load(force)
    Icons.measureTile()

    task.spawn(function()
        local HttpService = Env.service("HttpService")

        if not force then
            local cached = Env.readFile(CACHE_FILE)
            if cached then
                local ok, decoded = pcall(function()
                    return HttpService:JSONDecode(cached)
                end)
                if ok and type(decoded) == "table" and next(decoded) then
                    ingest(decoded)
                    return
                end
            end
        end

        local response = Env.httpRequest({ Url = METADATA_URL, Method = "GET" })
        if not response.ok then
            return
        end

        local map = parse(response.body)
        if not next(map) then
            return
        end

        local ok, encoded = pcall(function()
            return HttpService:JSONEncode(map)
        end)
        if ok then
            Env.writeFile(CACHE_FILE, encoded)
        end

        ingest(map)
    end)
end

--------------------------------------------------------------------------------
-- Lookup
--------------------------------------------------------------------------------

-- Classes without their own icon inherit their nearest ancestor's, which is how
-- Studio renders e.g. a WedgePart with the Part icon.
function Icons.indexFor(className)
    local cached = resolved[className]
    if cached then
        return cached
    end

    local current = className
    local guard = 0
    while current and guard < 40 do
        guard = guard + 1
        local index = indexByClass[current]
        if index then
            resolved[className] = index
            return index
        end
        current = ApiDump.superclassOf(current)
    end

    resolved[className] = FALLBACK_INDEX
    return FALLBACK_INDEX
end

function Icons.rectOffset(className)
    return Vector2.new(Icons.indexFor(className) * Icons.TILE, 0)
end

function Icons.rectSize()
    return Vector2.new(Icons.TILE, Icons.TILE)
end

-- Applies the sheet + rect to an existing ImageLabel.
function Icons.apply(imageLabel, className)
    imageLabel.Image = Icons.SHEET
    imageLabel.ImageRectSize = Icons.rectSize()
    imageLabel.ImageRectOffset = Icons.rectOffset(className)
end

function Icons.count()
    local total = 0
    for _ in pairs(indexByClass) do
        total = total + 1
    end
    return total
end

return Icons

