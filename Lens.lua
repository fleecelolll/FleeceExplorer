__lensModules["ui/vlist"] = function()
-- Virtualized fixed-height list.
--
-- Backs the explorer, the property grid and the script viewer. A game with
-- 200k instances still only ever costs us `visible + 1` row objects, and
-- because rows are assigned to pool slots by `index % poolSize`, scrolling by
-- one row rebinds exactly one row instead of the whole window.

local RunService = game:GetService("RunService")

local UI = __lensRequire("ui/base")
local Theme = __lensRequire("core/theme")
local Util = __lensRequire("core/util")

local VList = {}
VList.__index = VList

function VList.new(options)
    local self = setmetatable({}, VList)

    self.rowHeight = options.rowHeight or 20
    self.createRow = assert(options.createRow, "VList requires createRow")
    self.bindRow = assert(options.bindRow, "VList requires bindRow")
    self.unbindRow = options.unbindRow
    self.canvasWidth = options.canvasWidth or 0

    self.items = {}
    self.pool = {}
    self.poolSize = 0
    self.dirty = true
    self.maid = Util.Maid.new()

    self.scroll = UI.new("ScrollingFrame", {
        Size = options.Size or UDim2.fromScale(1, 1),
        Position = options.Position or UDim2.fromScale(0, 0),
        BackgroundTransparency = 1,
        BorderSizePixel = 0,
        ScrollBarThickness = 6,
        ScrollingDirection = options.scrollingDirection or Enum.ScrollingDirection.XY,
        CanvasSize = UDim2.new(),
        ClipsDescendants = true,
        ZIndex = options.ZIndex or 1,
        Parent = options.parent,
        theme = { ScrollBarImageColor3 = "scrollbar" },
    })

    self.content = UI.frame({
        Size = UDim2.fromScale(1, 1),
        BackgroundTransparency = 1,
        Parent = self.scroll,
    })

    self.maid:add(self.scroll:GetPropertyChangedSignal("CanvasPosition"):Connect(function()
        self.dirty = true
    end))
    self.maid:add(self.scroll:GetPropertyChangedSignal("AbsoluteSize"):Connect(function()
        self.dirty = true
    end))

    -- One coalesced update per frame; a scroll drag fires CanvasPosition many
    -- times per frame and we only want to pay for the last one.
    self.maid:add(RunService.Heartbeat:Connect(function()
        if self.dirty then
            self.dirty = false
            self:render()
        end
    end))

    self.maid:add(Theme.changed:connect(function()
        self:invalidate()
    end))

    return self
end

function VList:setItems(items)
    self.items = items or {}

    -- Resize the canvas now rather than waiting for the next render: a
    -- scrollToIndex issued in the same frame would otherwise be clamped
    -- against the previous, shorter canvas and land in the wrong place.
    self.scroll.CanvasSize = UDim2.new(0, self.canvasWidth, 0, #self.items * self.rowHeight)

    self:invalidate()
end

function VList:count()
    return #self.items
end

-- Forces every visible row to rebind on the next frame.
function VList:invalidate()
    for _, row in ipairs(self.pool) do
        row.itemIndex = nil
    end
    self.dirty = true
end

-- Cheaper than invalidate: keeps bindings, just schedules a re-render.
function VList:refresh()
    self.dirty = true
end

function VList:ensurePool(size)
    while self.poolSize < size do
        self.poolSize = self.poolSize + 1
        local row = self.createRow(self.poolSize)
        row.frame.Parent = self.content
        row.frame.Visible = false
        row.itemIndex = nil
        self.pool[self.poolSize] = row
    end
end

function VList:render()
    local rowHeight = self.rowHeight
    local count = #self.items
    local viewportHeight = self.scroll.AbsoluteSize.Y

    local canvasHeight = count * rowHeight
    local desiredCanvas = UDim2.new(0, self.canvasWidth, 0, canvasHeight)
    if self.scroll.CanvasSize ~= desiredCanvas then
        self.scroll.CanvasSize = desiredCanvas
    end

    if count == 0 or viewportHeight <= 0 then
        for _, row in ipairs(self.pool) do
            if row.frame.Visible then
                row.frame.Visible = false
                row.itemIndex = nil
                if self.unbindRow then
                    self.unbindRow(row)
                end
            end
        end
        return
    end

    local scrollTop = self.scroll.CanvasPosition.Y
    local firstIndex = math.max(1, math.floor(scrollTop / rowHeight) + 1)
    local visibleRows = math.ceil(viewportHeight / rowHeight) + 2
    local lastIndex = math.min(count, firstIndex + visibleRows - 1)

    self:ensurePool(visibleRows + 1)

    local used = {}
    for itemIndex = firstIndex, lastIndex do
        local slot = (itemIndex - 1) % self.poolSize + 1
        used[slot] = true

        local row = self.pool[slot]
        row.frame.Position = UDim2.new(0, 0, 0, (itemIndex - 1) * rowHeight)
        row.frame.Size = UDim2.new(1, self.canvasWidth > 0 and self.canvasWidth or 0, 0, rowHeight)

        if row.itemIndex ~= itemIndex then
            row.itemIndex = itemIndex
            self.bindRow(row, self.items[itemIndex], itemIndex)
        end

        if not row.frame.Visible then
            row.frame.Visible = true
        end
    end

    for slot = 1, self.poolSize do
        if not used[slot] then
            local row = self.pool[slot]
            if row.frame.Visible then
                row.frame.Visible = false
                row.itemIndex = nil
                if self.unbindRow then
                    self.unbindRow(row)
                end
            end
        end
    end
end

function VList:indexVisible(index)
    local rowHeight = self.rowHeight
    local top = self.scroll.CanvasPosition.Y
    local bottom = top + self.scroll.AbsoluteSize.Y
    local itemTop = (index - 1) * rowHeight
    return itemTop >= top and (itemTop + rowHeight) <= bottom
end

-- `mode` is "center" (default) or "nearest".
function VList:scrollToIndex(index, mode)
    local count = #self.items
    if count == 0 then
        return
    end
    index = Util.clamp(index, 1, count)

    local rowHeight = self.rowHeight
    local viewportHeight = self.scroll.AbsoluteSize.Y
    local itemTop = (index - 1) * rowHeight
    local target

    if mode == "nearest" then
        local top = self.scroll.CanvasPosition.Y
        if itemTop < top then
            target = itemTop
        elseif itemTop + rowHeight > top + viewportHeight then
            target = itemTop + rowHeight - viewportHeight
        else
            return
        end
    else
        target = itemTop - (viewportHeight / 2) + (rowHeight / 2)
    end

    local maxScroll = math.max(0, count * rowHeight - viewportHeight)
    self.scroll.CanvasPosition = Vector2.new(
        self.scroll.CanvasPosition.X,
        Util.clamp(target, 0, maxScroll)
    )
    self.dirty = true
end

function VList:setRowHeight(height)
    self.rowHeight = height
    self:invalidate()
end

function VList:setCanvasWidth(width)
    self.canvasWidth = width
    self.dirty = true
end

function VList:destroy()
    self.maid:clean()
    for _, row in ipairs(self.pool) do
        pcall(function()
            row.frame:Destroy()
        end)
    end
    self.pool = {}
    self.poolSize = 0
    pcall(function()
        self.scroll:Destroy()
    end)
end

return VList

end
