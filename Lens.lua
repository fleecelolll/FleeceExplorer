--------------------------------------------------------------------------------
-- Decompilation
--------------------------------------------------------------------------------

local function decompileRemote(scriptInstance, providerId)
    local bytecode, err = Env.scriptBytecode(scriptInstance)
    if not bytecode then
        return nil, err
    end

    local encoded = Env.base64Encode(bytecode)
    local response

    if providerId == "konstant" then
        response = Env.httpRequest({
            Url = "http://api.plusgiant5.com/konstant/decompile",
            Method = "POST",
            Headers = { ["Content-Type"] = "text/plain" },
            Body = bytecode,
        })
    else
        local HttpService = Env.service("HttpService")
        response = Env.httpRequest({
            Url = "https://api.lua.expert/decompile",
            Method = "POST",
            Headers = { ["Content-Type"] = "application/json" },
            Body = HttpService:JSONEncode({ script = encoded }),
        })
    end

    if not response.ok then
        return nil, response.err or "remote decompiler failed"
    end
    if response.body == "" then
        return nil, "remote decompiler returned nothing"
    end
    return response.body
end

function ScriptView.decompile(scriptInstance, providerId)
    providerId = providerId or (Config.get("decompiler.preferNative", true) and "native" or "luaexpert")

    if providerId == "native" then
        local source, err = Env.decompileScript(scriptInstance)
        if source then
            return source, "native"
        end
        -- Fall through to the network decompiler rather than giving up.
        local remote, remoteErr = decompileRemote(scriptInstance, "luaexpert")
        if remote then
            return remote, "lua.expert (native failed: " .. tostring(err) .. ")"
        end
        return nil, tostring(err) .. " / " .. tostring(remoteErr)
    end

    local source, err = decompileRemote(scriptInstance, providerId)
    if source then
        return source, providerId
    end
    return nil, err
end

