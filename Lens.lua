    local cached = serviceCache[name]
    if cached then
        return cached
    end
    local ok, svc = pcall(function()
        return game:GetService(name)
    end)
    if not ok or not svc then
        return nil
    end
    cached = ref(svc)
    serviceCache[name] = cached
    return cached
end

