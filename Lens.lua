local function splitLines(source)
    local result = {}
    for line in string.gmatch(source .. "\n", "([^\n]*)\n") do
        result[#result + 1] = (string.gsub(line, "\r", ""))
    end
    -- gmatch on the padded source yields one trailing empty entry.
    if #result > 0 and result[#result] == "" then
        result[#result] = nil
    end
    return result
end

local function longestLine()
    local longest = 0
    for _, line in ipairs(lines) do
        if #line > longest then
            longest = #line
        end
    end
    return longest
end

local function setSource(source)
    currentSource = source
    lines = splitLines(source)
    lineStates = Highlighter.computeLineStates(lines)
    list:setCanvasWidth(math.max(600, longestLine() * 7 + GUTTER + 20))
    list:setItems(lines)
end

