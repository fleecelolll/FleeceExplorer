        Text = "◢",
        TextSize = 11,
        TextXAlignment = Enum.TextXAlignment.Center,
        ZIndex = self.frame.ZIndex + 5,
        Parent = grip,
        theme = { TextColor3 = "textFaint" },
    })
    marks.Name = "Grip"

    local resizing = false
    local startInput, startSize

    grip.InputBegan:Connect(function(input)
        if input.UserInputType ~= Enum.UserInputType.MouseButton1 and input.UserInputType ~= Enum.UserInputType.Touch then
            return
        end
        resizing = true
        startInput = input.Position
        startSize = self.frame.AbsoluteSize
    end)

    UserInputService.InputChanged:Connect(function(input)
        if not resizing then
            return
        end
        if input.UserInputType ~= Enum.UserInputType.MouseMovement and input.UserInputType ~= Enum.UserInputType.Touch then
            return
        end
        local delta = input.Position - startInput
        self.frame.Size = UDim2.fromOffset(
            math.max(self.minSize.X, startSize.X + delta.X),
            math.max(self.minSize.Y, startSize.Y + delta.Y)
        )
    end)

    UserInputService.InputEnded:Connect(function(input)
        if not resizing then
            return
        end
        if input.UserInputType == Enum.UserInputType.MouseButton1 or input.UserInputType == Enum.UserInputType.Touch then
            resizing = false
            self:persist()
        end
    end)
end

function Window:bringToFront()
    topZIndex = topZIndex + 1
    local delta = topZIndex - self.frame.ZIndex
    if delta == 0 then
        return
    end

    -- Shift the whole subtree so relative stacking inside the window survives.
    local function shift(instance)
        for _, child in ipairs(instance:GetChildren()) do
            if child:IsA("GuiObject") then
                child.ZIndex = child.ZIndex + delta
                shift(child)
            end
        end
    end

    self.frame.ZIndex = topZIndex
    shift(self.frame)
end

function Window:setVisible(visible)
    if self.frame.Visible == visible then
        return
    end
    self.frame.Visible = visible
    if visible then
        self:bringToFront()
    end
    self:persist()
    self.visibleChanged:fire(visible)
end

function Window:isVisible()
    return self.frame.Visible
end

function Window:toggle()
    self:setVisible(not self.frame.Visible)
    return self.frame.Visible
end

function Window:setTitle(text)
    self.titleLabel.Text = text
end

-- Adds a small square button to the title bar's right cluster.
function Window:addHeaderButton(text, tooltip, onClick)
    local button = UI.new("TextButton", {
        Size = UDim2.fromOffset(20, 20),
        Text = text,
        Font = UI.FONT_MEDIUM,
        TextSize = 12,
        BackgroundTransparency = 1,
        AutoButtonColor = false,
        LayoutOrder = 10,
        ZIndex = self.frame.ZIndex + 3,
        Parent = self.headerRight,
    })
    UI.corner(button, 4)

    local active = false
    local function paint(hover)
        button.TextColor3 = (hover or active) and Theme.color("text") or Theme.color("textDim")
        button.BackgroundColor3 = active and Theme.color("accent") or Theme.color("bg3")
        button.BackgroundTransparency = (hover or active) and 0 or 1
    end
    UI.repaint(button, function()
        paint(false)
    end)
    button.MouseEnter:Connect(function()
        paint(true)
    end)
    button.MouseLeave:Connect(function()
        paint(false)
    end)
    button.MouseButton1Click:Connect(function()
        if onClick then
            onClick()
        end
    end)

    self.headerRight.Size = UDim2.new(0, self.headerRight.Size.X.Offset + 22, 1, 0)
    self.headerRight.Position = UDim2.new(1, -self.headerRight.Size.X.Offset - 4, 0, 0)
    self.titleLabel.Size = UDim2.new(1, -self.headerRight.Size.X.Offset - 14, 1, 0)

    return {
        instance = button,
        setActive = function(value)
            active = value == true
            paint(false)
        end,
    }
end

function Window.all()
    return openWindows
end

