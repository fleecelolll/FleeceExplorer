__lensModules["features/highlighter"] = function()
-- Luau syntax highlighter producing RichText, one label per line.
--
-- A single TextLabel holding a whole script chokes on tag count, so highlight
-- runs per visible line. Long strings and block comments span lines, so the
-- bracket state at the start of each line is computed once up front and the
-- per-line pass is then independent and cheap.

local Theme = __lensRequire("core/theme")

local Highlighter = {}

local KEYWORDS = {
    ["and"] = true, ["break"] = true, ["do"] = true, ["else"] = true,
    ["elseif"] = true, ["end"] = true, ["false"] = true, ["for"] = true,
    ["function"] = true, ["if"] = true, ["in"] = true, ["local"] = true,
    ["nil"] = true, ["not"] = true, ["or"] = true, ["repeat"] = true,
    ["return"] = true, ["then"] = true, ["true"] = true, ["until"] = true,
    ["while"] = true, ["continue"] = true, ["export"] = true, ["type"] = true,
}

local GLOBALS = {
    ["game"] = true, ["workspace"] = true, ["script"] = true, ["self"] = true,
    ["shared"] = true, ["_G"] = true, ["math"] = true, ["string"] = true,
    ["table"] = true, ["task"] = true, ["os"] = true, ["coroutine"] = true,
    ["pairs"] = true, ["ipairs"] = true, ["next"] = true, ["print"] = true,
    ["warn"] = true, ["error"] = true, ["assert"] = true, ["pcall"] = true,
    ["xpcall"] = true, ["select"] = true, ["type"] = true, ["typeof"] = true,
    ["tostring"] = true, ["tonumber"] = true, ["setmetatable"] = true,
    ["getmetatable"] = true, ["rawget"] = true, ["rawset"] = true,
    ["require"] = true, ["Instance"] = true, ["Vector3"] = true,
    ["Vector2"] = true, ["CFrame"] = true, ["Color3"] = true, ["UDim2"] = true,
    ["UDim"] = true, ["Enum"] = true, ["BrickColor"] = true, ["Ray"] = true,
    ["TweenInfo"] = true, ["NumberSequence"] = true, ["ColorSequence"] = true,
}

local PALETTE = {
    keyword = Color3.fromRGB(197, 134, 192),
    global = Color3.fromRGB(86, 156, 214),
    string = Color3.fromRGB(206, 145, 120),
    number = Color3.fromRGB(181, 206, 168),
    comment = Color3.fromRGB(106, 153, 85),
    operator = Color3.fromRGB(212, 212, 212),
    identifier = Color3.fromRGB(220, 220, 220),
    call = Color3.fromRGB(220, 220, 170),
}

local function hex(color)
    return string.format("#%02X%02X%02X", color.R * 255 + 0.5, color.G * 255 + 0.5, color.B * 255 + 0.5)
end

local function escape(text)
    text = string.gsub(text, "&", "&amp;")
    text = string.gsub(text, "<", "&lt;")
    text = string.gsub(text, ">", "&gt;")
    return text
end

local function span(text, color)
    if text == "" then
        return ""
    end
    return string.format('<font color="%s">%s</font>', hex(color), escape(text))
end

--------------------------------------------------------------------------------
-- Line state
--------------------------------------------------------------------------------

-- state: nil when normal, otherwise { kind = "comment"|"string", level = n }
local function closingPattern(level)
    return "%]" .. string.rep("=", level) .. "%]"
end

-- Scans a line and returns the state that the *next* line begins in.
local function scanLineState(line, state)
    local position = 1
    local length = #line

    while position <= length do
        if state then
            local closeStart, closeEnd = string.find(line, closingPattern(state.level), position)
            if closeStart then
                position = closeEnd + 1
                state = nil
            else
                return state
            end
        else
            local char = string.sub(line, position, position)

            if char == "-" and string.sub(line, position, position + 1) == "--" then
                local bracketLevel = string.match(line, "^%-%-%[(=*)%[", position)
                if bracketLevel then
                    state = { kind = "comment", level = #bracketLevel }
                    position = position + 4 + #bracketLevel
                else
                    return nil
                end
            elseif char == "[" then
                local bracketLevel = string.match(line, "^%[(=*)%[", position)
                if bracketLevel then
                    state = { kind = "string", level = #bracketLevel }
                    position = position + 2 + #bracketLevel
                else
                    position = position + 1
                end
            elseif char == '"' or char == "'" then
                local index = position + 1
                while index <= length do
                    local inner = string.sub(line, index, index)
                    if inner == "\\" then
                        index = index + 2
                    elseif inner == char then
                        break
                    else
                        index = index + 1
                    end
                end
                position = index + 1
            else
                position = position + 1
            end
        end
    end

    return state
end

-- One pass over the whole source recording the entry state of each line.
function Highlighter.computeLineStates(lines)
    local states = table.create(#lines + 1)
    local state = nil
    for index, line in ipairs(lines) do
        states[index] = state
        state = scanLineState(line, state)
    end
    return states
end

--------------------------------------------------------------------------------
-- Per-line highlight
--------------------------------------------------------------------------------

function Highlighter.line(line, state)
    if line == "" then
        return ""
    end

    local out = {}
    local position = 1
    local length = #line

    while position <= length do
        if state then
            local color = state.kind == "comment" and PALETTE.comment or PALETTE.string
            local closeStart, closeEnd = string.find(line, closingPattern(state.level), position)
            if closeStart then
                out[#out + 1] = span(string.sub(line, position, closeEnd), color)
                position = closeEnd + 1
                state = nil
            else
                out[#out + 1] = span(string.sub(line, position), color)
                position = length + 1
            end
        else
            local char = string.sub(line, position, position)

            -- Comments
            if string.sub(line, position, position + 1) == "--" then
                local bracketLevel = string.match(line, "^%-%-%[(=*)%[", position)
                if bracketLevel then
                    state = { kind = "comment", level = #bracketLevel }
                    local head = position + 4 + #bracketLevel - 1
                    out[#out + 1] = span(string.sub(line, position, head), PALETTE.comment)
                    position = head + 1
                else
                    out[#out + 1] = span(string.sub(line, position), PALETTE.comment)
                    position = length + 1
                end

            -- Long strings
            elseif char == "[" and string.match(line, "^%[(=*)%[", position) then
                local bracketLevel = string.match(line, "^%[(=*)%[", position)
                state = { kind = "string", level = #bracketLevel }
                local head = position + 2 + #bracketLevel - 1
                out[#out + 1] = span(string.sub(line, position, head), PALETTE.string)
                position = head + 1

            -- Quoted strings
            elseif char == '"' or char == "'" then
                local index = position + 1
                while index <= length do
                    local inner = string.sub(line, index, index)
                    if inner == "\\" then
                        index = index + 2
                    elseif inner == char then
                        break
                    else
                        index = index + 1
                    end
                end
                local stop = math.min(index, length)
                out[#out + 1] = span(string.sub(line, position, stop), PALETTE.string)
                position = stop + 1

            -- Numbers
            elseif string.match(char, "%d") or (char == "." and string.match(string.sub(line, position + 1, position + 1), "%d")) then
                local number = string.match(line, "^0[xX]%x+", position)
                    or string.match(line, "^%d*%.?%d+[eE]?[%+%-]?%d*", position)
                    or char
                out[#out + 1] = span(number, PALETTE.number)
                position = position + #number

            -- Identifiers
            elseif string.match(char, "[%a_]") then
                local word = string.match(line, "^[%a_][%w_]*", position)
                local color
                if KEYWORDS[word] then
                    color = PALETTE.keyword
                elseif GLOBALS[word] then
                    color = PALETTE.global
                elseif string.match(string.sub(line, position + #word), "^%s*%(") then
                    color = PALETTE.call
                else
                    color = PALETTE.identifier
                end
                out[#out + 1] = span(word, color)
                position = position + #word

            -- Whitespace runs through untouched.
            elseif char == " " or char == "\t" then
                local run = string.match(line, "^[ \t]+", position)
                out[#out + 1] = escape(run)
                position = position + #run

            else
                out[#out + 1] = span(char, PALETTE.operator)
                position = position + 1
            end
        end
    end

    return table.concat(out)
end

function Highlighter.plainColor()
    return Theme.color("text")
end

return Highlighter

end
__lensModules["features/nilinstances"] = function()
-- The synthetic "Nil Instances" root shown at the bottom of the explorer.
--
-- Detached instances have no parent to watch, so there is nothing to subscribe
-- to: the list is rescanned on demand and cached briefly, because the flatten
-- pass can ask for children many times per second.

local Config = __lensRequire("core/config")
local Env = __lensRequire("core/env")
local Root = __lensRequire("ui/root")
local Util = __lensRequire("core/util")

local NilInstances = {}

local CACHE_TTL = 3

local cache = {}
local cachedAt = 0
local lastSource = "none"

function NilInstances.scan(force)
    if not force and (os.clock() - cachedAt) < CACHE_TTL then
        return cache
    end

    local instances, source = Env.getNilInstances()
    lastSource = source

    -- On executors where gethui() hands back a detached container, our own UI
    -- is technically nil-parented and would flood this list with hundreds of
    -- our own frames. Filter ourselves out.
    local lensGui = Root.gui
    local function isOurs(instance)
        if not lensGui then
            return false
        end
        local ok, mine = pcall(function()
            return instance == lensGui or instance:IsDescendantOf(lensGui)
        end)
        return ok and mine
    end

    -- Only surface roots: if an instance's parent is also detached, it will
    -- appear under its parent instead of cluttering the top level.
    local set = {}
    for _, instance in ipairs(instances) do
        set[instance] = true
    end

    local roots = {}
    for _, instance in ipairs(instances) do
        if not isOurs(instance) then
            local ok, parent = pcall(function()
                return instance.Parent
            end)
            if not ok or parent == nil or not set[parent] then
                roots[#roots + 1] = instance
            end
        end
    end

    table.sort(roots, function(a, b)
        local nameA, nameB = Util.safeName(a), Util.safeName(b)
        if nameA == nameB then
            return Util.safeClass(a) < Util.safeClass(b)
        end
        return nameA < nameB
    end)

    cache = roots
    cachedAt = os.clock()
    return cache
end

function NilInstances.refresh()
    return NilInstances.scan(true)
end

function NilInstances.count()
    return #cache
end

function NilInstances.source()
    return lastSource
end

function NilInstances.descriptor()
    return {
        label = "Nil Instances",
        hint = function()
            return tostring(#cache)
        end,
        visible = function()
            return Config.get("explorer.showNilFolder", true)
        end,
        children = function()
            return NilInstances.scan(false)
        end,
    }
end

return NilInstances

end
__lensModules["features/picker"] = function()
-- Click-to-select pickers for world parts and GUI objects.

local RunService = game:GetService("RunService")
local UserInputService = game:GetService("UserInputService")

local Env = __lensRequire("core/env")
local Root = __lensRequire("ui/root")
local Theme = __lensRequire("core/theme")
local Toast = __lensRequire("ui/toast")
local UI = __lensRequire("ui/base")
local Util = __lensRequire("core/util")

local Picker = {}

Picker.modeChanged = Util.Signal.new()

local Players = Env.service("Players")
local localPlayer = Players and Players.LocalPlayer

local partMode = false
local guiMode = false

local hoverHighlight = nil
local hoverOutline = nil
local hoverLabel = nil
local renderConnection = nil
local inputConnection = nil
local currentTarget = nil

--------------------------------------------------------------------------------
-- Hover chrome
--------------------------------------------------------------------------------

local function ensureChrome()
    if not hoverHighlight then
        hoverHighlight = Instance.new("Highlight")
        hoverHighlight.FillTransparency = 0.6
        hoverHighlight.OutlineTransparency = 0
        hoverHighlight.DepthMode = Enum.HighlightDepthMode.AlwaysOnTop
        hoverHighlight.Enabled = false
        hoverHighlight.Parent = Root.gui
    end

    if not hoverOutline then
        hoverOutline = UI.frame({
            Name = "PickerOutline",
            BackgroundTransparency = 1,
            Visible = false,
            ZIndex = 880,
            Parent = Root.tooltip,
        })
        local stroke = Instance.new("UIStroke")
        stroke.Thickness = 2
        stroke.Parent = hoverOutline
    end

    if not hoverLabel then
        hoverLabel = UI.frame({
            Name = "PickerLabel",
            Size = UDim2.fromOffset(10, 20),
            AutomaticSize = Enum.AutomaticSize.X,
            Visible = false,
            ZIndex = 885,
            Parent = Root.tooltip,
            theme = { BackgroundColor3 = "bg0" },
        })
        UI.corner(hoverLabel, 4)
        UI.stroke(hoverLabel, "accent", 1)

        UI.label({
            Name = "Text",
            Size = UDim2.new(0, 0, 1, 0),
            AutomaticSize = Enum.AutomaticSize.X,
            Position = UDim2.fromOffset(6, 0),
            TextSize = 12,
            ZIndex = 886,
            Parent = hoverLabel,
        })
        UI.padding(hoverLabel, 0, 6, 0, 0)
    end
end

local function setLabel(text, position)
    if not hoverLabel then
        return
    end
    hoverLabel.Text.Text = text
    hoverLabel.Position = UDim2.fromOffset(position.X + 16, position.Y + 16)
    hoverLabel.Visible = true
end

local function clearChrome()
    if hoverHighlight then
        hoverHighlight.Enabled = false
        hoverHighlight.Adornee = nil
    end
    if hoverOutline then
        hoverOutline.Visible = false
    end
    if hoverLabel then
        hoverLabel.Visible = false
    end
    currentTarget = nil
end

--------------------------------------------------------------------------------
-- Hit testing
--------------------------------------------------------------------------------

local function partUnderCursor()
    if not localPlayer then
        return nil
    end
    local ok, mouse = pcall(function()
        return localPlayer:GetMouse()
    end)
    if not ok or not mouse then
        return nil
    end
    return mouse.Target
end

-- Walks every BasePlayerGui we can reach, topmost first. Our own UI is skipped
-- so the picker never selects itself.
local function guiUnderCursor()
    local position = UserInputService:GetMouseLocation()

    local containers = {}
    if localPlayer then
        local playerGui = localPlayer:FindFirstChildOfClass("PlayerGui")
        if playerGui then
            containers[#containers + 1] = playerGui
        end
    end
    local coreGui = Env.service("CoreGui")
    if coreGui then
        containers[#containers + 1] = coreGui
    end

    for _, container in ipairs(containers) do
        local ok, found = pcall(function()
            return container:GetGuiObjectsAtPosition(position.X, position.Y)
        end)
        if ok and found then
            for _, object in ipairs(found) do
                if not object:IsDescendantOf(Root.gui) then
                    return object
                end
            end
        end
    end

    return nil
end

--------------------------------------------------------------------------------
-- Loop
--------------------------------------------------------------------------------

local function stopLoop()
    if renderConnection then
        renderConnection:Disconnect()
        renderConnection = nil
    end
    if inputConnection then
        inputConnection:Disconnect()
        inputConnection = nil
    end
    clearChrome()
end

local function selectTarget()
    if not currentTarget then
        return
    end

    local Explorer = __lensRequire("panels/explorer")
    local target = currentTarget

    Explorer.clearSearchAndJump(target)
    Toast.show("Selected " .. Util.safeName(target))
end

local function startLoop()
    if renderConnection then
        return
    end
    ensureChrome()

    renderConnection = RunService.RenderStepped:Connect(function()
        local accent = Theme.color("accent")
        local position = UserInputService:GetMouseLocation()

        if guiMode then
            local object = guiUnderCursor()
            if object then
                currentTarget = object
                hoverHighlight.Enabled = false
                hoverOutline.Visible = true
                hoverOutline.UIStroke.Color = accent
                hoverOutline.Position = UDim2.fromOffset(object.AbsolutePosition.X, object.AbsolutePosition.Y)
                hoverOutline.Size = UDim2.fromOffset(object.AbsoluteSize.X, object.AbsoluteSize.Y)
                setLabel(Util.safeName(object) .. "  (" .. Util.safeClass(object) .. ")", position)
                return
            end
            hoverOutline.Visible = false
        end

        if partMode then
            local part = partUnderCursor()
            if part then
                currentTarget = part
                hoverOutline.Visible = false
                hoverHighlight.FillColor = accent
                hoverHighlight.OutlineColor = accent
                hoverHighlight.Adornee = part
                hoverHighlight.Enabled = true
                setLabel(Util.safeName(part) .. "  (" .. Util.safeClass(part) .. ")", position)
                return
            end
            hoverHighlight.Enabled = false
        end

        currentTarget = nil
        if hoverLabel then
            hoverLabel.Visible = false
        end
    end)

    inputConnection = UserInputService.InputBegan:Connect(function(input, gameProcessed)
        if input.UserInputType ~= Enum.UserInputType.MouseButton1 then
            return
        end
        if gameProcessed then
            return
        end
        if not currentTarget then
            return
        end
        selectTarget()
    end)
end

--------------------------------------------------------------------------------
-- Public
--------------------------------------------------------------------------------

local function sync()
    if partMode or guiMode then
        startLoop()
    else
        stopLoop()
    end
    Picker.modeChanged:fire(partMode, guiMode)
end

function Picker.setPartMode(enabled)
    partMode = enabled == true
    sync()
end

function Picker.setGuiMode(enabled)
    guiMode = enabled == true
    sync()
end

function Picker.togglePart()
    Picker.setPartMode(not partMode)
    return partMode
end

function Picker.toggleGui()
    Picker.setGuiMode(not guiMode)
    return guiMode
end

function Picker.partMode()
    return partMode
end

function Picker.guiMode()
    return guiMode
end

return Picker

end
__lensModules["features/serialize"] = function()
-- Value formatting and parsing for every datatype the property grid can show.

local Env = __lensRequire("core/env")
local Util = __lensRequire("core/util")

local ApiDump = __lensRequire("core/apidump")

local Serialize = {}

local n = Util.formatNumber

--------------------------------------------------------------------------------
-- Display text
--------------------------------------------------------------------------------

function Serialize.toText(value)
    local kind = typeof(value)

    if value == nil then
        return "nil"
    elseif kind == "string" then
        return value
    elseif kind == "boolean" then
        return value and "true" or "false"
    elseif kind == "number" then
        return n(value)
    elseif kind == "Vector3" then
        return string.format("%s, %s, %s", n(value.X), n(value.Y), n(value.Z))
    elseif kind == "Vector2" then
        return string.format("%s, %s", n(value.X), n(value.Y))
    elseif kind == "Vector3int16" or kind == "Vector2int16" then
        return tostring(value)
    elseif kind == "UDim" then
        return string.format("%s, %s", n(value.Scale), n(value.Offset))
    elseif kind == "UDim2" then
        return string.format(
            "{%s, %s}, {%s, %s}",
            n(value.X.Scale), n(value.X.Offset),
            n(value.Y.Scale), n(value.Y.Offset)
        )
    elseif kind == "Color3" then
        return string.format("%d, %d, %d", value.R * 255 + 0.5, value.G * 255 + 0.5, value.B * 255 + 0.5)
    elseif kind == "BrickColor" then
        return value.Name
    elseif kind == "CFrame" then
        local position = value.Position
        local rx, ry, rz = value:ToOrientation()
        return string.format(
            "%s, %s, %s  |  %s, %s, %s",
            n(position.X), n(position.Y), n(position.Z),
            n(math.deg(rx)), n(math.deg(ry)), n(math.deg(rz))
        )
    elseif kind == "EnumItem" then
        return value.Name
    elseif kind == "Enum" then
        return tostring(value)
    elseif kind == "Instance" then
        return Util.safeName(value) .. " (" .. Util.safeClass(value) .. ")"
    elseif kind == "NumberRange" then
        return string.format("%s, %s", n(value.Min), n(value.Max))
    elseif kind == "Rect" then
        return string.format("%s, %s, %s, %s", n(value.Min.X), n(value.Min.Y), n(value.Max.X), n(value.Max.Y))
    elseif kind == "NumberSequence" then
        local parts = {}
        for _, keypoint in ipairs(value.Keypoints) do
            parts[#parts + 1] = string.format("%s:%s", n(keypoint.Time), n(keypoint.Value))
        end
        return table.concat(parts, "  ")
    elseif kind == "ColorSequence" then
        local parts = {}
        for _, keypoint in ipairs(value.Keypoints) do
            local color = keypoint.Value
            parts[#parts + 1] = string.format(
                "%s:(%d,%d,%d)",
                n(keypoint.Time), color.R * 255 + 0.5, color.G * 255 + 0.5, color.B * 255 + 0.5
            )
        end
        return table.concat(parts, "  ")
    elseif kind == "PhysicalProperties" then
        return string.format(
            "%s, %s, %s, %s, %s",
            n(value.Density), n(value.Friction), n(value.Elasticity),
            n(value.FrictionWeight), n(value.ElasticityWeight)
        )
    elseif kind == "Faces" then
        local faces = {}
        for _, face in ipairs({ "Top", "Bottom", "Left", "Right", "Front", "Back" }) do
            if value[face] then
                faces[#faces + 1] = face
            end
        end
        return #faces > 0 and table.concat(faces, ", ") or "none"
    elseif kind == "Axes" then
        local axes = {}
        for _, axis in ipairs({ "X", "Y", "Z" }) do
            if value[axis] then
                axes[#axes + 1] = axis
            end
        end
        return #axes > 0 and table.concat(axes, ", ") or "none"
    elseif kind == "Ray" then
        return string.format("%s -> %s", tostring(value.Origin), tostring(value.Direction))
    elseif kind == "Font" then
        return tostring(value.Family) .. " " .. tostring(value.Weight)
    end

    return tostring(value)
end

--------------------------------------------------------------------------------
-- Lua literals
--------------------------------------------------------------------------------

function Serialize.toLua(value)
    local kind = typeof(value)

    if value == nil then
        return "nil"
    elseif kind == "string" then
        return Util.quoteString(value)
    elseif kind == "boolean" then
        return value and "true" or "false"
    elseif kind == "number" then
        return n(value)
    elseif kind == "Vector3" then
        return string.format("Vector3.new(%s, %s, %s)", n(value.X), n(value.Y), n(value.Z))
    elseif kind == "Vector2" then
        return string.format("Vector2.new(%s, %s)", n(value.X), n(value.Y))
    elseif kind == "UDim" then
        return string.format("UDim.new(%s, %s)", n(value.Scale), n(value.Offset))
    elseif kind == "UDim2" then
        return string.format(
            "UDim2.new(%s, %s, %s, %s)",
            n(value.X.Scale), n(value.X.Offset), n(value.Y.Scale), n(value.Y.Offset)
        )
    elseif kind == "Color3" then
        return string.format(
            "Color3.fromRGB(%d, %d, %d)",
            value.R * 255 + 0.5, value.G * 255 + 0.5, value.B * 255 + 0.5
        )
    elseif kind == "BrickColor" then
        return string.format("BrickColor.new(%s)", Util.quoteString(value.Name))
    elseif kind == "CFrame" then
        local components = { value:GetComponents() }
        local parts = {}
        for index, component in ipairs(components) do
            parts[index] = n(component)
        end
        return string.format("CFrame.new(%s)", table.concat(parts, ", "))
    elseif kind == "EnumItem" then
        return tostring(value)
    elseif kind == "Instance" then
        return Util.instancePath(value)
    elseif kind == "NumberRange" then
        return string.format("NumberRange.new(%s, %s)", n(value.Min), n(value.Max))
    elseif kind == "Rect" then
        return string.format(
            "Rect.new(%s, %s, %s, %s)",
            n(value.Min.X), n(value.Min.Y), n(value.Max.X), n(value.Max.Y)
        )
    elseif kind == "NumberSequence" then
        local parts = {}
        for _, keypoint in ipairs(value.Keypoints) do
            parts[#parts + 1] = string.format(
                "NumberSequenceKeypoint.new(%s, %s, %s)",
                n(keypoint.Time), n(keypoint.Value), n(keypoint.Envelope)
            )
        end
        return string.format("NumberSequence.new({%s})", table.concat(parts, ", "))
    elseif kind == "ColorSequence" then
        local parts = {}
        for _, keypoint in ipairs(value.Keypoints) do
            parts[#parts + 1] = string.format(
                "ColorSequenceKeypoint.new(%s, %s)",
                n(keypoint.Time), Serialize.toLua(keypoint.Value)
            )
        end
        return string.format("ColorSequence.new({%s})", table.concat(parts, ", "))
    elseif kind == "PhysicalProperties" then
        return string.format(
            "PhysicalProperties.new(%s, %s, %s, %s, %s)",
            n(value.Density), n(value.Friction), n(value.Elasticity),
            n(value.FrictionWeight), n(value.ElasticityWeight)
        )
    elseif kind == "Faces" then
        local faces = {}
        for _, face in ipairs({ "Top", "Bottom", "Left", "Right", "Front", "Back" }) do
            if value[face] then
                faces[#faces + 1] = "Enum.NormalId." .. face
            end
        end
        return string.format("Faces.new(%s)", table.concat(faces, ", "))
    elseif kind == "Axes" then
        local axes = {}
        for _, axis in ipairs({ "X", "Y", "Z" }) do
            if value[axis] then
                axes[#axes + 1] = "Enum.Axis." .. axis
            end
        end
        return string.format("Axes.new(%s)", table.concat(axes, ", "))
    elseif kind == "Font" then
        return string.format(
            "Font.new(%s, %s, %s)",
            Util.quoteString(tostring(value.Family)), tostring(value.Weight), tostring(value.Style)
        )
    end

    return "--[[" .. kind .. "]] nil"
end

--------------------------------------------------------------------------------
-- Parsing
--------------------------------------------------------------------------------

local function numbersIn(text, expected)
    local values = {}
    for match in string.gmatch(text, "-?%d*%.?%d+e?-?%d*") do
        values[#values + 1] = tonumber(match)
    end
    if expected and #values < expected then
        return nil
    end
    return values
end

-- Returns value, error. `current` supplies the shape for partial edits.
function Serialize.parse(text, typeName, current)
    text = text or ""
    local trimmed = string.match(text, "^%s*(.-)%s*$")

    if typeName == "string" or typeName == "Content" or typeName == "ProtectedString" then
        return text
    elseif typeName == "bool" then
        local lowered = string.lower(trimmed)
        if lowered == "true" or lowered == "1" or lowered == "yes" then
            return true
        elseif lowered == "false" or lowered == "0" or lowered == "no" then
            return false
        end
        return nil, "expected true or false"
    elseif typeName == "int" or typeName == "int64" then
        local value = tonumber(trimmed)
        if not value then
            return nil, "expected a number"
        end
        return math.floor(value + 0.5)
    elseif typeName == "float" or typeName == "double" then
        local value = tonumber(trimmed)
        if not value then
            return nil, "expected a number"
        end
        return value
    elseif typeName == "Vector3" then
        local values = numbersIn(trimmed, 3)
        if not values then
            return nil, "expected x, y, z"
        end
        return Vector3.new(values[1], values[2], values[3])
    elseif typeName == "Vector2" then
        local values = numbersIn(trimmed, 2)
        if not values then
            return nil, "expected x, y"
        end
        return Vector2.new(values[1], values[2])
    elseif typeName == "UDim" then
        local values = numbersIn(trimmed, 2)
        if not values then
            return nil, "expected scale, offset"
        end
        return UDim.new(values[1], values[2])
    elseif typeName == "UDim2" then
        local values = numbersIn(trimmed, 4)
        if not values then
            return nil, "expected xScale, xOffset, yScale, yOffset"
        end
        return UDim2.new(values[1], values[2], values[3], values[4])
    elseif typeName == "Color3" then
        local hex = string.match(trimmed, "^#?(%x%x%x%x%x%x)$")
        if hex then
            return Color3.fromRGB(
                tonumber(string.sub(hex, 1, 2), 16),
                tonumber(string.sub(hex, 3, 4), 16),
                tonumber(string.sub(hex, 5, 6), 16)
            )
        end
        local values = numbersIn(trimmed, 3)
        if not values then
            return nil, "expected r, g, b"
        end
        -- Values above 1 are read as 0-255, matching how they are displayed.
        local maxValue = math.max(values[1], values[2], values[3])
        if maxValue > 1 then
            return Color3.fromRGB(values[1], values[2], values[3])
        end
        return Color3.new(values[1], values[2], values[3])
    elseif typeName == "BrickColor" then
        local ok, color = pcall(function()
            return BrickColor.new(trimmed)
        end)
        if not ok then
            return nil, "unknown BrickColor"
        end
        return color
    elseif typeName == "CFrame" then
        local values = numbersIn(trimmed)
        if #values >= 12 then
            return CFrame.new(table.unpack(values, 1, 12))
        elseif #values >= 6 then
            return CFrame.new(values[1], values[2], values[3])
                * CFrame.fromOrientation(math.rad(values[4]), math.rad(values[5]), math.rad(values[6]))
        elseif #values >= 3 then
            local rotation = current and (current - current.Position) or CFrame.identity
            return CFrame.new(values[1], values[2], values[3]) * rotation
        end
        return nil, "expected x, y, z"
    elseif typeName == "NumberRange" then
        local values = numbersIn(trimmed, 1)
        if not values then
            return nil, "expected min, max"
        end
        return NumberRange.new(values[1], values[2] or values[1])
    elseif typeName == "Rect" then
        local values = numbersIn(trimmed, 4)
        if not values then
            return nil, "expected minX, minY, maxX, maxY"
        end
        return Rect.new(values[1], values[2], values[3], values[4])
    elseif typeName == "PhysicalProperties" then
        local values = numbersIn(trimmed, 3)
        if not values then
            return nil, "expected density, friction, elasticity[, weights]"
        end
        return PhysicalProperties.new(
            values[1], values[2], values[3],
            values[4] or 1, values[5] or 1
        )
    end

    return nil, "type is not editable here"
end

function Serialize.parseEnum(enumName, text)
    local ok, enum = pcall(function()
        return Enum[enumName]
    end)
    if not ok or not enum then
        return nil, "unknown enum"
    end
    for _, item in ipairs(enum:GetEnumItems()) do
        if item.Name == text then
            return item
        end
    end
    return nil, "not a member of " .. enumName
end

