local __lensModules = {}
local __lensCache = {}
local function __lensRequire(name)
    local cached = __lensCache[name]
    if cached ~= nil then
        return cached
    end
    local factory = __lensModules[name]
    if factory == nil then
        error("Lens: unknown module '" .. tostring(name) .. "'", 2)
    end
    local result = factory()
    if result == nil then
        result = true
    end
    __lensCache[name] = result
    return result
end

__lensModules["core/apidump"] = function()
-- Roblox API dump: the property list for a class.
--
-- Luau has no runtime reflection for instances, so the only way to know that a
-- Part has an "Anchored" is to read the published dump. It is cached to disk
-- after the first fetch; decoding the 7MB payload measures at ~40ms, so a cold
-- start is dominated by the network, not the parse.

local Env = __lensRequire("core/env")
local Util = __lensRequire("core/util")

local HttpService = Env.service("HttpService")

local ApiDump = {}

ApiDump.ready = false
ApiDump.loading = false
ApiDump.error = nil
ApiDump.readyChanged = Util.Signal.new()

local DUMP_URL = "https://raw.githubusercontent.com/MaximumADHD/Roblox-Client-Tracker/roblox/API-Dump.json"
local CACHE_FILE = "api-dump.json"

local classes = {}
local resolvedCache = {}

-- Properties that exist in the dump but cannot be read from a script context,
-- or that are pure noise in an explorer.
local SKIP_TAGS = {
    NotScriptable = true,
}

local function tagSet(tags)
    local set = {}
    if type(tags) == "table" then
        for _, tag in ipairs(tags) do
            set[tag] = true
        end
    end
    return set
end

local function securityOf(member)
    local security = member.Security
    if type(security) == "string" then
        return security, security
    end
    if type(security) == "table" then
        return security.Read or "None", security.Write or "None"
    end
    return "None", "None"
end

local function ingest(dump)
    classes = {}
    resolvedCache = {}

    for _, class in ipairs(dump.Classes or {}) do
        local properties = {}

        for _, member in ipairs(class.Members or {}) do
            if member.MemberType == "Property" then
                local tags = tagSet(member.Tags)

                local skip = false
                for tag in pairs(SKIP_TAGS) do
                    if tags[tag] then
                        skip = true
                        break
                    end
                end

                if not skip then
                    local readSecurity, writeSecurity = securityOf(member)
                    local valueType = member.ValueType or {}
                    properties[#properties + 1] = {
                        name = member.Name,
                        typeName = valueType.Name or "unknown",
                        typeCategory = valueType.Category or "Primitive",
                        category = member.Category or "Data",
                        readOnly = tags.ReadOnly == true or writeSecurity ~= "None",
                        deprecated = tags.Deprecated == true,
                        hidden = tags.Hidden == true or tags.NotBrowsable == true,
                        notReplicated = tags.NotReplicated == true,
                        readSecurity = readSecurity,
                        writeSecurity = writeSecurity,
                    }
                end
            end
        end

        classes[class.Name] = {
            name = class.Name,
            superclass = class.Superclass,
            properties = properties,
        }
    end

    ApiDump.ready = true
    ApiDump.loading = false
    ApiDump.error = nil
    ApiDump.readyChanged:fire(true)
end

local function decode(body)
    local ok, dump = pcall(function()
        return HttpService:JSONDecode(body)
    end)
    if ok and type(dump) == "table" and dump.Classes then
        return dump
    end
    return nil
end

function ApiDump.load(force)
    if ApiDump.loading or (ApiDump.ready and not force) then
        return
    end
    ApiDump.loading = true

    task.spawn(function()
        if not force then
            local cached = Env.readFile(CACHE_FILE)
            if cached then
                local dump = decode(cached)
                if dump then
                    ingest(dump)
                    return
                end
            end
        end

        local response = Env.httpRequest({ Url = DUMP_URL, Method = "GET" })
        if not response.ok then
            ApiDump.loading = false
            ApiDump.error = response.err or "download failed"
            ApiDump.readyChanged:fire(false)
            return
        end

        local dump = decode(response.body)
        if not dump then
            ApiDump.loading = false
            ApiDump.error = "could not parse API dump"
            ApiDump.readyChanged:fire(false)
            return
        end

        Env.writeFile(CACHE_FILE, response.body)
        ingest(dump)
    end)
end

function ApiDump.refresh()
    ApiDump.ready = false
    ApiDump.load(true)
end

-- Walks the superclass chain; a subclass redeclaration wins over the parent's.
function ApiDump.propertiesFor(className)
    if not ApiDump.ready then
        return {}
    end

    local cached = resolvedCache[className]
    if cached then
        return cached
    end

    local collected = {}
    local seen = {}
    local current = className
    local guard = 0

    while current and current ~= "<<<ROOT>>>" and guard < 64 do
        guard = guard + 1
        local class = classes[current]
        if not class then
            break
        end
        for _, property in ipairs(class.properties) do
            if not seen[property.name] then
                seen[property.name] = true
                collected[#collected + 1] = property
            end
        end
        current = class.superclass
    end

    table.sort(collected, function(a, b)
        if a.category == b.category then
            return a.name < b.name
        end
        return a.category < b.category
    end)

    resolvedCache[className] = collected
    return collected
end

function ApiDump.superclassOf(className)
    local class = classes[className]
    return class and class.superclass or nil
end

function ApiDump.classNames()
    local names = {}
    for name in pairs(classes) do
        names[#names + 1] = name
    end
    table.sort(names)
    return names
end

function ApiDump.classCount()
    local count = 0
    for _ in pairs(classes) do
        count = count + 1
    end
    return count
end

return ApiDump

end
