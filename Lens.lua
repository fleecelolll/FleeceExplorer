        Size = UDim2.fromOffset(width, height),
        Position = UDim2.fromOffset(x, y),
        ZIndex = 601,
        Parent = blocker,
        theme = { BackgroundColor3 = "bg1" },
    })
    UI.corner(panel, 10)
    UI.stroke(panel, "border", 1)

    blocker.MouseButton1Click:Connect(function()
        Widgets.closePopup()
