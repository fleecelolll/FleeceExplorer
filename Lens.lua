local function clearAdornments()
    for _, highlight in ipairs(highlights) do
        pcall(function()
            highlight:Destroy()
        end)
    end
    table.clear(highlights)

    for _, box in ipairs(guiBoxes) do
        pcall(function()
            box:Destroy()
        end)
