__lensModules["core/tree"] = function()
-- Instance tree model.
--
-- Two decisions carry the performance of the whole explorer:
--
--  1. We never enumerate the DataModel. Flattening only descends into nodes the
--     user has actually expanded, so the flat list is proportional to what is
--     on screen, not to the size of the place.
--
--  2. ChildAdded/ChildRemoved are bound per expanded node, not globally on
--     game.DescendantAdded. A busy game fires descendant events thousands of
--     times a second; binding narrowly means we are woken only for subtrees the
--     user is actually looking at.

local Config = __lensRequire("core/config")
local Env = __lensRequire("core/env")
local Util = __lensRequire("core/util")

local Tree = {}

Tree.changed = Util.Signal.new()
Tree.flat = {}
Tree.frozen = false
Tree.freezeFilter = nil

local expanded = {}
local nodeCache = setmetatable({}, { __mode = "k" })
local connections = {}
local pinned = {}
local pendingRebuild = false
local virtualRoots = {}

-- Top-level order, mirroring Studio's explorer. Workspace is always first;
-- everything not listed here is an internal service and goes into the
-- "Services" group at the bottom rather than burying the useful containers in
-- a 140-entry alphabetical dump.
local PRIMARY_SERVICES = {
    "Workspace",
    "Players",
    "Lighting",
    "MaterialService",
    "ReplicatedFirst",
    "ReplicatedStorage",
    "ServerScriptService",
    "ServerStorage",
    "StarterGui",
    "StarterPack",
    "StarterPlayer",
    "Teams",
    "SoundService",
    "TextChatService",
    "Chat",
    "LocalizationService",
    "TestService",
    "CoreGui",
    "CorePackages",
    "Debris",
}

local PRIMARY_LOOKUP = {}
for order, name in ipairs(PRIMARY_SERVICES) do
    PRIMARY_LOOKUP[name] = order
end

-- Services worth resolving even when they are not already children of game.
local EXTRA_SERVICES = {
    "CoreGui", "CorePackages", "Players", "Lighting", "ReplicatedStorage",
    "ReplicatedFirst", "StarterGui", "StarterPack", "StarterPlayer", "SoundService",
    "Chat", "TextChatService", "TweenService", "UserInputService", "RunService",
    "HttpService", "MarketplaceService", "TeleportService", "CollectionService",
    "PathfindingService", "PhysicsService", "Debris", "ContextActionService",
    "GuiService", "Stats", "LogService", "TestService", "VRService",
    "ProximityPromptService", "VoiceChatService", "MaterialService", "Teams",
    "LocalizationService", "ServerScriptService", "ServerStorage",
}

--------------------------------------------------------------------------------
-- Nodes
--------------------------------------------------------------------------------

local function nodeFor(instance)
    local node = nodeCache[instance]
    if not node then
        node = { instance = instance, depth = 0, expandable = false, removed = false }
        nodeCache[instance] = node
    end
    return node
end

function Tree.addVirtualRoot(descriptor)
    virtualRoots[#virtualRoots + 1] = descriptor
    return descriptor
end

--------------------------------------------------------------------------------
-- Roots
--------------------------------------------------------------------------------

local function hiddenServices()
    local hidden = Config.get("explorer.hiddenServices", {})
    local set = {}
    if type(hidden) == "table" then
        for _, name in ipairs(hidden) do
            set[name] = true
        end
        -- JSON round-trips an empty array as an object; tolerate both shapes.
        for name, value in pairs(hidden) do
            if type(name) == "string" and value == true then
                set[name] = true
            end
        end
    end
    return set
end

-- Every reachable service, keyed by ClassName.
--
-- Dedupe by ClassName, not instance identity: Env.service() hands back a
-- cloneref'd handle, which is a different Lua value to the one in
-- game:GetChildren() even though it is the same service. Services are
-- singletons per class, so the class name is the reliable key.
local function serviceMap()
    local hidden = hiddenServices()
    local byClass = {}

    local ok, children = pcall(function()
        return game:GetChildren()
    end)
    if ok then
        for _, child in ipairs(children) do
            local className = Util.safeClass(child)
            if not byClass[className] and not hidden[className] then
                byClass[className] = child
            end
        end
    end

    for _, name in ipairs(EXTRA_SERVICES) do
        if not hidden[name] and not byClass[name] then
            local service = Env.service(name)
            if service then
                byClass[name] = service
            end
        end
    end

    return byClass
end

function Tree.roots()
    if Config.get("explorer.hideAllServices", false) then
        return {}
    end

    local byClass = serviceMap()
    local roots = {}

    -- Studio order, not alphabetical: Workspace first.
    for _, name in ipairs(PRIMARY_SERVICES) do
        local service = byClass[name]
        if service then
            roots[#roots + 1] = service
        end
    end

    return roots
end

-- Everything that did not earn a top-level slot, alphabetical.
function Tree.secondaryServices()
    if Config.get("explorer.hideAllServices", false) then
        return {}
    end

    local byClass = serviceMap()
    local rest = {}

    for className, service in pairs(byClass) do
        if not PRIMARY_LOOKUP[className] then
            rest[#rest + 1] = service
        end
    end

    table.sort(rest, function(a, b)
        return Util.safeName(a) < Util.safeName(b)
    end)

    return rest
end

function Tree.isPrimaryService(instance)
    return PRIMARY_LOOKUP[Util.safeClass(instance)] ~= nil
end

--------------------------------------------------------------------------------
-- Children
--------------------------------------------------------------------------------

local SORT_LIMIT = 800

function Tree.childrenOf(instance)
    local ok, children = pcall(function()
        return instance:GetChildren()
    end)
    if not ok then
        return {}
    end

    -- Sorting a folder with tens of thousands of children costs more than it is
    -- worth; above the limit we keep native child order.
    if Config.get("ui.sortChildren", false) and #children <= SORT_LIMIT then
        table.sort(children, function(a, b)
            local nameA, nameB = Util.safeName(a), Util.safeName(b)
            if nameA == nameB then
                return Util.safeClass(a) < Util.safeClass(b)
            end
            return nameA < nameB
        end)
    end

    local kept = pinned[instance]
    if kept and #kept > 0 then
        local present = {}
        for _, child in ipairs(children) do
            present[child] = true
        end
        for _, held in ipairs(kept) do
            if not present[held] then
                children[#children + 1] = held
            end
        end
    end

    return children
end

local function hasChildren(instance)
    local ok, children = pcall(function()
        return instance:GetChildren()
    end)
    if ok and #children > 0 then
        return true
    end
    local kept = pinned[instance]
    return kept ~= nil and #kept > 0
end

--------------------------------------------------------------------------------
-- Event binding
--------------------------------------------------------------------------------

local function matchesFreezeFilter(instance)
    local filter = Tree.freezeFilter
    if not filter or not filter.value or filter.value == "" then
        return false
    end

    if filter.mode == "class" then
        local className = Util.safeClass(instance)
        if filter.exact then
            return className == filter.value
        end
        return string.find(string.lower(className), string.lower(filter.value), 1, true) ~= nil
    end

    local name = Util.safeName(instance)
    if filter.exact then
        return name == filter.value
    end
    return string.find(string.lower(name), string.lower(filter.value), 1, true) ~= nil
end

local function pin(parent, instance)
    local list = pinned[parent]
    if not list then
        list = {}
        pinned[parent] = list
    end
    for _, held in ipairs(list) do
        if held == instance then
            return
        end
    end
    -- Strong reference: this is what stops the instance being collected so the
    -- user can still inspect it after the game removed it.
    list[#list + 1] = instance
end

local function scheduleRebuild()
    if Tree.frozen or pendingRebuild then
        return
    end
    pendingRebuild = true
    task.defer(function()
        pendingRebuild = false
        if not Tree.frozen then
            Tree.rebuild()
        end
    end)
end

local function bindNode(instance)
    if connections[instance] then
        return
    end

    local maid = Util.Maid.new()
    local ok = pcall(function()
        maid:add(instance.ChildAdded:Connect(function()
            scheduleRebuild()
        end))
        maid:add(instance.ChildRemoved:Connect(function(child)
            if matchesFreezeFilter(child) then
                pin(instance, child)
            end
            scheduleRebuild()
        end))
    end)

    if ok then
        connections[instance] = maid
    else
        maid:clean()
    end
end

local function unbindNode(instance)
    local maid = connections[instance]
    if maid then
        maid:clean()
        connections[instance] = nil
    end
end

function Tree.unbindAll()
    for instance, maid in pairs(connections) do
        maid:clean()
        connections[instance] = nil
    end
end

--------------------------------------------------------------------------------
-- Expansion
--------------------------------------------------------------------------------

function Tree.isExpanded(instance)
    return expanded[instance] == true
end

function Tree.expand(instance, skipRebuild)
    if expanded[instance] then
        return
    end
    expanded[instance] = true
    bindNode(instance)
    if not skipRebuild then
        Tree.rebuild()
    end
end

function Tree.collapse(instance, skipRebuild)
    if not expanded[instance] then
        return
    end
    expanded[instance] = nil
    unbindNode(instance)
    if not skipRebuild then
        Tree.rebuild()
    end
end

function Tree.toggle(instance)
    if expanded[instance] then
        Tree.collapse(instance)
    else
        Tree.expand(instance)
    end
end

function Tree.collapseAll()
    for instance in pairs(expanded) do
        unbindNode(instance)
    end
    table.clear(expanded)
    Tree.rebuild()
end

-- Expands every ancestor so `instance` becomes visible in the flat list.
function Tree.revealPath(instance)
    local chain = {}
    local current = instance
    local guard = 0
    while current and guard < 512 do
        guard = guard + 1
        local ok, parent = pcall(function()
            return current.Parent
        end)
        if not ok or not parent or parent == game then
            break
        end
        chain[#chain + 1] = parent
        current = parent
    end

    -- `current` is now the top-level service. If it is not one of the primary
    -- containers it lives inside the Services group, which has to be open for
    -- the row to exist in the flat list.
    if current and Tree.servicesDescriptor and not Tree.isPrimaryService(current) then
        local ok, parent = pcall(function()
            return current.Parent
        end)
        if ok and parent == game then
            Tree.expand(Tree.servicesDescriptor, true)
        end
    end

    for index = #chain, 1, -1 do
        Tree.expand(chain[index], true)
    end
    Tree.rebuild()
end

-- Expands a whole subtree, bounded so an accidental click on Workspace does not
-- lock the client up.
function Tree.expandDescendants(instance, maxNodes)
    maxNodes = maxNodes or 2000
    local count = 0

    local function walk(target)
        if count >= maxNodes then
            return
        end
        local children = Tree.childrenOf(target)
        if #children == 0 then
            return
        end
        Tree.expand(target, true)
        count = count + 1
        for _, child in ipairs(children) do
            if count >= maxNodes then
                return
            end
            walk(child)
        end
    end

    walk(instance)
    Tree.rebuild()
    return count
end

--------------------------------------------------------------------------------
-- Flatten
--------------------------------------------------------------------------------

local function appendNode(list, instance, depth, removedFlag)
    local node = nodeFor(instance)
    node.depth = depth
    node.expandable = hasChildren(instance)
    node.removed = removedFlag or false
    node.virtual = false
    list[#list + 1] = node
    return node
end

local function flattenInstance(list, instance, depth, liveSet)
    local node = appendNode(list, instance, depth, liveSet ~= nil and not liveSet[instance])

    if not expanded[instance] then
        return
    end

    local children = Tree.childrenOf(instance)
    if #children == 0 then
        return
    end

    -- Build the live set once per expanded node so pinned-but-removed children
    -- can be flagged without an O(n^2) membership test.
    local live
    local kept = pinned[instance]
    if kept and #kept > 0 then
        live = {}
        local ok, realChildren = pcall(function()
            return instance:GetChildren()
        end)
        if ok then
            for _, child in ipairs(realChildren) do
                live[child] = true
            end
        end
    end

    for _, child in ipairs(children) do
        flattenInstance(list, child, depth + 1, live)
    end
end

function Tree.rebuild()
    local list = {}

    for _, root in ipairs(Tree.roots()) do
        flattenInstance(list, root, 0, nil)
    end

    for _, descriptor in ipairs(virtualRoots) do
        if descriptor.visible == nil or descriptor.visible() then
            local node = {
                virtual = true,
                descriptor = descriptor,
                depth = 0,
                expandable = true,
                removed = false,
                instance = nil,
            }
            list[#list + 1] = node

            if expanded[descriptor] then
                for _, child in ipairs(descriptor.children()) do
                    flattenInstance(list, child, 1, nil)
                end
            end
        end
    end

    Tree.flat = list
    Tree.changed:fire(list)
    return list
end

--------------------------------------------------------------------------------
-- Freeze
--------------------------------------------------------------------------------

function Tree.setFrozen(frozen)
    if Tree.frozen == frozen then
        return
    end
    Tree.frozen = frozen
    if not frozen then
        Tree.rebuild()
    end
end

function Tree.setFreezeFilter(mode, value, exact)
    if not value or value == "" then
        Tree.freezeFilter = nil
        return
    end
    Tree.freezeFilter = { mode = mode, value = value, exact = exact == true }
end

function Tree.clearPinned()
    table.clear(pinned)
    Tree.rebuild()
end

function Tree.pinnedCount()
    local total = 0
    for _, list in pairs(pinned) do
        total = total + #list
    end
    return total
end

-- Index of an instance in the current flat list, or nil when it is collapsed
-- out of view.
function Tree.indexOf(instance)
    for index, node in ipairs(Tree.flat) do
        if node.instance == instance then
            return index
        end
    end
    return nil
end

function Tree.init()
    -- New services appearing under game are rare but cheap to watch for.
    bindNode(game)
    Tree.rebuild()
end

return Tree

end
__lensModules["core/util"] = function()
-- Shared helpers: signals, value formatting, instance paths, scheduling.

local Util = {}

--------------------------------------------------------------------------------
-- Signal
--------------------------------------------------------------------------------

local Signal = {}
Signal.__index = Signal

function Signal.new()
    return setmetatable({ handlers = {} }, Signal)
end

function Signal:connect(handler)
    local handlers = self.handlers
    handlers[#handlers + 1] = handler
    local connection = {}
    function connection:disconnect()
        for index, candidate in ipairs(handlers) do
            if candidate == handler then
                table.remove(handlers, index)
                break
            end
        end
    end
    connection.Disconnect = connection.disconnect
    return connection
end

function Signal:fire(...)
    -- Iterate a copy so handlers may disconnect themselves during dispatch.
    local snapshot = table.clone(self.handlers)
    for _, handler in ipairs(snapshot) do
        local ok, err = pcall(handler, ...)
        if not ok then
            warn("[Lens] signal handler error: " .. tostring(err))
        end
    end
end

function Signal:destroy()
    table.clear(self.handlers)
end

Util.Signal = Signal

--------------------------------------------------------------------------------
-- Connection bag
--------------------------------------------------------------------------------

local Maid = {}
Maid.__index = Maid

function Maid.new()
    return setmetatable({ items = {} }, Maid)
end

function Maid:add(item)
    self.items[#self.items + 1] = item
    return item
end

function Maid:clean()
    local items = self.items
    self.items = {}
    for index = #items, 1, -1 do
        local item = items[index]
        local ok = pcall(function()
            if typeof(item) == "RBXScriptConnection" then
                item:Disconnect()
            elseif typeof(item) == "Instance" then
                item:Destroy()
            elseif type(item) == "function" then
                item()
            elseif type(item) == "table" then
                if item.disconnect then
                    item:disconnect()
                elseif item.Disconnect then
                    item:Disconnect()
                elseif item.destroy then
                    item:destroy()
                end
            end
        end)
        if not ok then
            -- A dead connection is not worth reporting.
        end
    end
end

Maid.destroy = Maid.clean
Util.Maid = Maid

--------------------------------------------------------------------------------
-- Misc
--------------------------------------------------------------------------------

function Util.clamp(value, minimum, maximum)
    if value < minimum then
        return minimum
    elseif value > maximum then
        return maximum
    end
    return value
end

function Util.round(value, places)
    local factor = 10 ^ (places or 0)
    return math.floor(value * factor + 0.5) / factor
end

-- Numbers in property fields: trim float noise but never lose precision that
-- the user typed in.
function Util.formatNumber(value)
    if value ~= value then
        return "nan"
    end
    if value == math.huge then
        return "inf"
    end
    if value == -math.huge then
        return "-inf"
    end
    if value % 1 == 0 and math.abs(value) < 1e15 then
        return string.format("%d", value)
    end
    local text = string.format("%.6g", value)
    return text
end

function Util.deepCopy(value)
    if type(value) ~= "table" then
        return value
    end
    local copy = {}
    for key, item in pairs(value) do
        copy[key] = Util.deepCopy(item)
    end
    return copy
end

function Util.merge(base, override)
    local result = Util.deepCopy(base)
    if type(override) ~= "table" then
        return result
    end
    for key, value in pairs(override) do
        if type(value) == "table" and type(result[key]) == "table" then
            result[key] = Util.merge(result[key], value)
        else
            result[key] = Util.deepCopy(value)
        end
    end
    return result
end

function Util.escapePattern(text)
    return (string.gsub(text, "([%^%$%(%)%%%.%[%]%*%+%-%?])", "%%%1"))
end

-- Roblox names are only valid as `a.b` when they are identifiers; everything
-- else has to go through bracket indexing to round-trip correctly.
function Util.isIdentifier(name)
    return string.match(name, "^[%a_][%w_]*$") ~= nil
end

function Util.quoteString(text)
    local escaped = string.gsub(text, "\\", "\\\\")
    escaped = string.gsub(escaped, '"', '\\"')
    escaped = string.gsub(escaped, "\n", "\\n")
    escaped = string.gsub(escaped, "\r", "\\r")
    escaped = string.gsub(escaped, "\t", "\\t")
    return '"' .. escaped .. '"'
end

-- Builds a Lua expression that resolves back to the instance.
function Util.instancePath(instance)
    if instance == nil then
        return "nil"
    end
    if instance == game then
        return "game"
    end

    local segments = {}
    local current = instance
    local guard = 0

    while current and current ~= game and guard < 256 do
        guard = guard + 1
        local ok, name = pcall(function()
            return current.Name
        end)
        if not ok then
            name = "?"
        end

        local parentOk, parent = pcall(function()
            return current.Parent
        end)
        if not parentOk then
            parent = nil
        end

        if parent == game then
            -- Services are reached through GetService, which survives renames.
            local classOk, className = pcall(function()
                return current.ClassName
            end)
            table.insert(segments, 1, string.format("game:GetService(%s)", Util.quoteString(classOk and className or name)))
            return table.concat(segments, "")
        end

        if Util.isIdentifier(name) then
            table.insert(segments, 1, "." .. name)
        else
            table.insert(segments, 1, "[" .. Util.quoteString(name) .. "]")
        end

        current = parent
    end

    if current == game then
        return "game" .. table.concat(segments, "")
    end

    -- Detached from the DataModel: the path is descriptive only.
    local ok, name = pcall(function()
        return instance.Name
    end)
    return string.format("--[[nil]] %s", ok and name or "Instance")
end

function Util.safeName(instance)
    local ok, name = pcall(function()
        return instance.Name
    end)
    if ok and type(name) == "string" then
        return name
    end
    return "???"
end

function Util.safeClass(instance)
    local ok, className = pcall(function()
        return instance.ClassName
    end)
    if ok and type(className) == "string" then
        return className
    end
    return "Instance"
end

function Util.isAlive(instance)
    if typeof(instance) ~= "Instance" then
        return false
    end
    local ok = pcall(function()
        return instance.Parent
    end)
    return ok
end

--------------------------------------------------------------------------------
-- Scheduling
--------------------------------------------------------------------------------

-- Collapses a burst of calls into one call on the next frame boundary.
function Util.throttled(interval, callback)
    local scheduled = false
    local lastRun = 0
    return function(...)
        if scheduled then
            return
        end
        local remaining = interval - (os.clock() - lastRun)
        scheduled = true
        local args = table.pack(...)
        task.delay(math.max(remaining, 0), function()
            scheduled = false
            lastRun = os.clock()
            callback(table.unpack(args, 1, args.n))
        end)
    end
end

function Util.debounced(delaySeconds, callback)
    local token = 0
    return function(...)
        token = token + 1
        local current = token
        local args = table.pack(...)
        task.delay(delaySeconds, function()
            if current ~= token then
                return
            end
            callback(table.unpack(args, 1, args.n))
        end)
    end
end

return Util

