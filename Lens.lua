local nativeBase64
if crypt and type(crypt.base64encode) == "function" then
    nativeBase64 = crypt.base64encode
elseif crypt and type(crypt.base64) == "table" and type(crypt.base64.encode) == "function" then
    nativeBase64 = crypt.base64.encode
elseif type(base64_encode) == "function" then
    nativeBase64 = base64_encode
elseif base64 and type(base64.encode) == "function" then
    nativeBase64 = base64.encode
end
Env.has.base64 = nativeBase64 ~= nil

local ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"

local function fallbackBase64(data)
    local parts = {}
    local length = #data
    local index = 1
    while index <= length do
        local a = string.byte(data, index) or 0
        local b = string.byte(data, index + 1)
        local c = string.byte(data, index + 2)
        local packed = a * 65536 + (b or 0) * 256 + (c or 0)

        local c1 = math.floor(packed / 262144) % 64
        local c2 = math.floor(packed / 4096) % 64
        local c3 = math.floor(packed / 64) % 64
        local c4 = packed % 64

        parts[#parts + 1] = string.sub(ALPHABET, c1 + 1, c1 + 1)
        parts[#parts + 1] = string.sub(ALPHABET, c2 + 1, c2 + 1)
        parts[#parts + 1] = b and string.sub(ALPHABET, c3 + 1, c3 + 1) or "="
        parts[#parts + 1] = c and string.sub(ALPHABET, c4 + 1, c4 + 1) or "="

        index = index + 3
    end
    return table.concat(parts)
end

function Env.base64Encode(data)
    if nativeBase64 then
        local ok, encoded = pcall(nativeBase64, data)
        if ok and type(encoded) == "string" then
            return encoded
        end
    end
    return fallbackBase64(data)
end

