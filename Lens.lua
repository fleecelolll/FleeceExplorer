-- Only bound rows are polled, so the cost is bounded by the visible window
-- rather than the property count.
local function startPolling()
    if pollThread then
        return
    end
    pollThread = task.spawn(function()
        while true do
            local rate = Config.get("properties.pollRate", 10)
            task.wait(1 / math.max(rate, 1))

            if Config.get("properties.liveUpdate", true)
                and window and window:isVisible()
                and target and list then
                for _, row in ipairs(list.pool) do
                    if row.frame.Visible and row.entry then
                        Properties.refreshRow(row)
                    end
                end
            end
        end
    end)
end

