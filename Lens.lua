-- Not every executor delivers LogService.MessageOut (several sandbox it, and
-- GetLogHistory then comes back empty too). Where it is dead we fall back to
-- hooking the global print/warn, restoring them on unload.

local hooks = {}
local capturedVia = "none"

local function joinArguments(...)
    local count = select("#", ...)
    local parts = table.create(count)
    for index = 1, count do
        parts[index] = tostring((select(index, ...)))
    end
    return table.concat(parts, "  ")
end

local function tryLogService()
    if not LogService then
        return false
    end

    local historyOk, history = pcall(function()
        return LogService:GetLogHistory()
    end)

    local delivered = false
    local connection
    local ok = pcall(function()
        connection = LogService.MessageOut:Connect(function(message, messageType)
            delivered = true
            push(message, TYPE_MAP[messageType] or "output")
        end)
    end)
    if not ok then
        return false
    end

    if historyOk and history and #history > 0 then
        for _, item in ipairs(history) do
            entries[#entries + 1] = {
                text = item.message,
                level = TYPE_MAP[item.messageType] or "output",
                clock = item.timestamp,
            }
        end
        applyFilter()
        return true, connection
    end

    -- No history to prove it works; probe it before trusting it.
    return nil, connection, function()
        return delivered
    end
end

local function hookGlobals()
    if type(hookfunction) ~= "function" then
        return false
    end

    local environment = (type(getrenv) == "function") and getrenv() or nil
    local targets = { { name = "print", level = "output" }, { name = "warn", level = "warning" } }

    for _, target in ipairs(targets) do
        local original = environment and rawget(environment, target.name) or nil
        if type(original) ~= "function" then
            original = target.name == "print" and print or warn
        end

        local ok = pcall(function()
            local callOriginal
            callOriginal = hookfunction(original, function(...)
                push(joinArguments(...), target.level)
                return callOriginal(...)
            end)
            hooks[#hooks + 1] = { original = original, callOriginal = callOriginal }
        end)

        if not ok then
            return false
        end
    end

    return #hooks > 0
end

function Console.attachSources()
    local ok, connection, probe = tryLogService()

    if ok == true then
        capturedVia = "LogService"
        return
    end

    if probe then
        -- Give MessageOut a moment to prove itself, then fall back if silent.
        task.spawn(function()
            print("[Lens] console attached")
            task.wait(0.5)
            if probe() then
                capturedVia = "LogService"
                return
            end
            if connection then
                pcall(function()
                    connection:Disconnect()
                end)
            end
            capturedVia = hookGlobals() and "hookfunction" or "none"
            if capturedVia == "none" then
                push("[Lens] this executor exposes no output stream; the Run box still works.", "warning")
            else
                push("[Lens] capturing print/warn directly (LogService is sandboxed here).", "info")
            end
        end)
        return
    end

    capturedVia = hookGlobals() and "hookfunction" or "none"
end

function Console.detachSources()
    for _, hook in ipairs(hooks) do
        pcall(function()
            hookfunction(hook.original, hook.callOriginal)
        end)
    end
    table.clear(hooks)
end

function Console.capturedVia()
    return capturedVia
end

--------------------------------------------------------------------------------
-- Execution
--------------------------------------------------------------------------------

function Console.execute(source)
    if source == "" then
        return
    end

    push("> " .. source, "info")

    local compiled, compileError = loadstring(source, "@LensConsole")
    if not compiled then
        push(tostring(compileError), "error")
        return
    end

    task.spawn(function()
        local ok, result = pcall(compiled)
        if not ok then
            push(tostring(result), "error")
        elseif result ~= nil then
            push("= " .. tostring(result), "output")
        end
    end)
end

