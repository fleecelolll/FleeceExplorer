__lensModules["core/search"] = function()
-- Incremental instance search.
--
-- A blind game:GetDescendants() is a visible freeze in a large place, so the
-- walk runs on an explicit stack with a per-frame time budget and yields when
-- it runs out. Narrowing an existing query filters the previous result set
-- instead of rescanning.

local RunService = game:GetService("RunService")

local Config = __lensRequire("core/config")
local Env = __lensRequire("core/env")
local Util = __lensRequire("core/util")

local Search = {}

Search.changed = Util.Signal.new()
Search.results = {}
Search.query = ""
Search.running = false
Search.scanned = 0

local generation = 0
local lastCompletedQuery = nil
local lastCompletedResults = nil
local lastClassFilterKey = ""

--------------------------------------------------------------------------------
-- Matching
--------------------------------------------------------------------------------

local function classFilterKey(filter)
    if not filter or #filter == 0 then
        return ""
    end
    local copy = table.clone(filter)
    table.sort(copy)
    return table.concat(copy, ",")
end

local function buildMatcher(query, classFilter)
    local caseSensitive = Config.get("search.caseSensitive", false)
    local needle = caseSensitive and query or string.lower(query)
    local hasQuery = needle ~= ""
    local hasClasses = classFilter and #classFilter > 0

    return function(instance)
        if hasClasses then
            local matchedClass = false
            for _, className in ipairs(classFilter) do
                local ok, isA = pcall(function()
                    return instance:IsA(className)
                end)
                if ok and isA then
                    matchedClass = true
                    break
                end
            end
            if not matchedClass then
                return false
            end
        end

        if not hasQuery then
            return hasClasses
        end

        local name = Util.safeName(instance)
        if not caseSensitive then
            name = string.lower(name)
        end
        if string.find(name, needle, 1, true) then
            return true
        end

        -- Typing a class name should also find instances of that class.
        local className = Util.safeClass(instance)
        if not caseSensitive then
            className = string.lower(className)
        end
        return string.find(className, needle, 1, true) ~= nil
    end
end

--------------------------------------------------------------------------------
-- Scanning
--------------------------------------------------------------------------------

function Search.cancel()
    generation = generation + 1
    Search.running = false
end

function Search.clear()
    Search.cancel()
    Search.query = ""
    Search.results = {}
    Search.scanned = 0
    lastCompletedQuery = nil
    lastCompletedResults = nil
    Search.changed:fire(Search.results, false)
end

function Search.run(query, options)
    options = options or {}
    generation = generation + 1
    local myGeneration = generation

    query = query or ""
    Search.query = query

    local classFilter = options.classFilter or Config.get("search.classFilter", {})
    local filterKey = classFilterKey(classFilter)

    if query == "" and filterKey == "" then
        Search.results = {}
        Search.running = false
        Search.changed:fire(Search.results, false)
        return
    end

    local matcher = buildMatcher(query, classFilter)

    -- Narrowing an existing query: filter what we already found.
    if
        lastCompletedQuery
        and filterKey == lastClassFilterKey
        and #query > #lastCompletedQuery
        and string.sub(string.lower(query), 1, #lastCompletedQuery) == string.lower(lastCompletedQuery)
        and lastCompletedResults
    then
        local narrowed = {}
        for _, instance in ipairs(lastCompletedResults) do
            if Util.isAlive(instance) and matcher(instance) then
                narrowed[#narrowed + 1] = instance
            end
        end
        Search.results = narrowed
        Search.running = false
        lastCompletedQuery = query
        lastCompletedResults = narrowed
        Search.changed:fire(narrowed, false)
        return
    end

    lastClassFilterKey = filterKey
    Search.running = true
    Search.scanned = 0
    Search.results = {}

    task.spawn(function()
        local budget = Config.get("search.budgetMs", 0.8) / 1000
        local results = {}
        local stack = {}
        local scanned = 0

        local ok, roots = pcall(function()
            return game:GetChildren()
        end)
        if ok then
            for _, root in ipairs(roots) do
                stack[#stack + 1] = root
            end
        end

        if Config.get("search.includeNil", true) then
            local nilInstances = Env.getNilInstances()
            for _, instance in ipairs(nilInstances) do
                stack[#stack + 1] = instance
            end
        end

        local sliceStart = os.clock()

        while #stack > 0 do
            if generation ~= myGeneration then
                return
            end

            local instance = stack[#stack]
            stack[#stack] = nil
            scanned = scanned + 1

            if matcher(instance) then
                results[#results + 1] = instance
            end

            local childrenOk, children = pcall(function()
                return instance:GetChildren()
            end)
            if childrenOk then
                for _, child in ipairs(children) do
                    stack[#stack + 1] = child
                end
            end

            if os.clock() - sliceStart >= budget then
                Search.results = results
                Search.scanned = scanned
                Search.changed:fire(results, true)
                RunService.Heartbeat:Wait()
                if generation ~= myGeneration then
                    return
                end
                sliceStart = os.clock()
            end
        end

        if generation ~= myGeneration then
            return
        end

        Search.results = results
        Search.scanned = scanned
        Search.running = false
        lastCompletedQuery = query
        lastCompletedResults = results
        Search.changed:fire(results, false)
    end)
end

--------------------------------------------------------------------------------
-- Class filter discovery
--------------------------------------------------------------------------------

-- Samples the place to offer a realistic class list rather than all 900 classes
-- from the API dump.
function Search.sampleClasses(limit)
    limit = limit or 40000
    local counts = {}
    local stack = {}

    local ok, roots = pcall(function()
        return game:GetChildren()
    end)
    if ok then
        for _, root in ipairs(roots) do
            stack[#stack + 1] = root
        end
    end

    local scanned = 0
    while #stack > 0 and scanned < limit do
        local instance = stack[#stack]
        stack[#stack] = nil
        scanned = scanned + 1

        local className = Util.safeClass(instance)
        counts[className] = (counts[className] or 0) + 1

        local childrenOk, children = pcall(function()
            return instance:GetChildren()
        end)
        if childrenOk then
            for _, child in ipairs(children) do
                stack[#stack + 1] = child
            end
        end
    end

    local list = {}
    for className, count in pairs(counts) do
        list[#list + 1] = { name = className, count = count }
    end
    table.sort(list, function(a, b)
        if a.count == b.count then
            return a.name < b.name
        end
        return a.count > b.count
    end)

    return list
end

return Search

end
