    window = Window.new({
        id = "viewer3d",
        title = "Object Viewer",
        width = 316,
        height = 176,
        x = 692,
        y = 524,
        minSize = Vector2.new(220, 150),
        visible = false,
        parent = Root.main,
    })
    Viewer.window = window

    local content = window.content

    local toolbar = UI.frame({
        Size = UDim2.new(1, 0, 0, TOOLBAR),
        BackgroundTransparency = 1,
        ZIndex = 3,
        Parent = content,
    })

    local rotateToggle = Widgets.checkbox({
        Size = UDim2.fromOffset(110, 20),
        Position = UDim2.fromOffset(6, 3),
        Text = "Auto-rotate",
        value = true,
        ZIndex = 4,
        Parent = toolbar,
        onChanged = function(value)
            autoRotate = value
        end,
    })

    local fit = Widgets.button({
        Size = UDim2.fromOffset(50, 20),
        Position = UDim2.fromOffset(120, 3),
        Text = "Fit",
        variant = "ghost",
        ZIndex = 4,
        Parent = toolbar,
        onClick = function()
            if target then
                Viewer.open(target)
            end
        end,
    })
    fit.Name = "Fit"

    statusLabel = UI.label({
        Size = UDim2.new(1, -180, 0, 20),
        Position = UDim2.fromOffset(176, 3),
        Text = "",
        TextSize = 11,
        TextXAlignment = Enum.TextXAlignment.Right,
        ZIndex = 4,
        Parent = toolbar,
        theme = { TextColor3 = "textFaint" },
    })

    viewport = UI.new("ViewportFrame", {
        Size = UDim2.new(1, -12, 1, -TOOLBAR - 8),
        Position = UDim2.fromOffset(6, TOOLBAR),
        BorderSizePixel = 0,
        Ambient = Color3.fromRGB(150, 150, 150),
        LightColor = Color3.fromRGB(255, 255, 255),
        LightDirection = Vector3.new(-0.4, -1, -0.2),
        ZIndex = 3,
        Parent = content,
        theme = { BackgroundColor3 = "bg2" },
    })
    UI.corner(viewport, 4)

    worldModel = Instance.new("WorldModel")
    worldModel.Parent = viewport

    camera = Instance.new("Camera")
    camera.FieldOfView = 55
    camera.Parent = viewport
    viewport.CurrentCamera = camera

    -- Orbit / zoom
    local dragging = false
    local lastPosition

    viewport.InputBegan:Connect(function(input)
        if input.UserInputType == Enum.UserInputType.MouseButton1 or input.UserInputType == Enum.UserInputType.Touch then
            dragging = true
            lastPosition = input.Position
            autoRotate = false
            rotateToggle.set(false, true)
        end
    end)

    UserInputService.InputChanged:Connect(function(input)
        if dragging and (input.UserInputType == Enum.UserInputType.MouseMovement or input.UserInputType == Enum.UserInputType.Touch) then
            local delta = input.Position - lastPosition
            lastPosition = input.Position
            yaw = yaw - delta.X * 0.01
            pitch = Util.clamp(pitch + delta.Y * 0.01, -1.5, 1.5)
            updateCamera()
        end
    end)

    UserInputService.InputEnded:Connect(function(input)
        if input.UserInputType == Enum.UserInputType.MouseButton1 or input.UserInputType == Enum.UserInputType.Touch then
            dragging = false
        end
    end)

    viewport.InputChanged:Connect(function(input)
        if input.UserInputType == Enum.UserInputType.MouseWheel then
            distance = Util.clamp(distance * (input.Position.Z > 0 and 0.85 or 1.18), 1, 5000)
            updateCamera()
        end
    end)

    task.spawn(function()
        while window do
            task.wait(1 / 30)
            if autoRotate and window:isVisible() and target then
                yaw = yaw + 0.012
                updateCamera()
            end
        end
    end)

    return window
end

function Viewer.open(instance)
    if not window then
        Viewer.build()
    end

    target = instance
    window:setTitle("Viewer - " .. Util.safeName(instance))
    window:setVisible(true)

    worldModel:ClearAllChildren()

    local clone = cloneForPreview(instance)
    if not clone then
        statusLabel.Text = "cannot clone"
        Toast.show("That instance refused to clone")
        return
    end

    clone.Parent = worldModel

    local center, size = boundsOf(clone)
    pivot = center

    -- Frame the object against the camera's vertical FOV rather than guessing a
    -- multiplier, so small parts and large models both fill the viewport.
    local extent = math.max(size.X, size.Y, size.Z, 0.5)
    local halfFov = math.rad(camera.FieldOfView) / 2
    distance = math.max((extent / 2) / math.tan(halfFov) * 1.35, 1.5)

    -- Anchor everything so physics does not pull the preview apart.
    for _, descendant in ipairs(clone:GetDescendants()) do
        pcall(function()
            if descendant:IsA("BasePart") then
                descendant.Anchored = true
            end
        end)
    end
    pcall(function()
        if clone:IsA("BasePart") then
            clone.Anchored = true
        end
    end)

    updateCamera()

    local partCount = 0
    for _, descendant in ipairs(clone:GetDescendants()) do
        local ok, isPart = pcall(function()
            return descendant:IsA("BasePart")
        end)
        if ok and isPart then
            partCount = partCount + 1
        end
    end
    local selfOk, selfIsPart = pcall(function()
        return clone:IsA("BasePart")
    end)
    if selfOk and selfIsPart then
        partCount = partCount + 1
    end

    statusLabel.Text = partCount .. " parts"
    local _ = Theme
end

function Viewer.close()
    if window then
        window:setVisible(false)
    end
    target = nil
    if worldModel then
        worldModel:ClearAllChildren()
    end
end

return Viewer

end
__lensModules["ui/base"] = function()
-- Instance construction with theme binding baked in.

local Theme = __lensRequire("core/theme")

local UI = {}

UI.FONT = Enum.Font.Gotham
UI.FONT_MEDIUM = Enum.Font.GothamMedium
UI.FONT_BOLD = Enum.Font.GothamBold
UI.FONT_CODE = Enum.Font.Code

-- props.theme maps property name -> theme role, e.g.
--   theme = { BackgroundColor3 = "bg1", BackgroundTransparency = "trans:panel" }
-- Roles are registered rather than resolved, so a later theme switch repaints
-- this object without rebuilding it.
function UI.new(className, props)
    local instance = Instance.new(className)
    props = props or {}

    local themeMap = props.theme
    local children = props.children
    local parent = props.Parent

    for key, value in pairs(props) do
        if key ~= "theme" and key ~= "children" and key ~= "Parent" then
            local ok, err = pcall(function()
                instance[key] = value
            end)
            if not ok then
                warn(("[Lens] could not set %s.%s: %s"):format(className, tostring(key), tostring(err)))
            end
        end
    end

    if themeMap then
        for property, role in pairs(themeMap) do
            Theme.register(instance, property, role)
        end
    end

    if children then
        for _, child in ipairs(children) do
            child.Parent = instance
        end
    end

    if parent then
        instance.Parent = parent
    end

    return instance
end

-- For widgets whose colour depends on interaction state (hover, pressed,
-- active) rather than a single role. The handler self-disconnects once the
-- instance is gone, so transient widgets do not leak into the theme signal.
function UI.repaint(instance, paint)
    paint()
    local connection
    connection = Theme.changed:connect(function()
        local alive, parent = pcall(function()
            return instance.Parent
        end)
        if not alive or parent == nil then
            connection:disconnect()
            return
        end
        paint()
    end)
    return connection
end

function UI.corner(parent, radius)
    return UI.new("UICorner", {
        CornerRadius = UDim.new(0, radius or 6),
        Parent = parent,
    })
end

function UI.stroke(parent, role, thickness)
    return UI.new("UIStroke", {
        Thickness = thickness or 1,
        ApplyStrokeMode = Enum.ApplyStrokeMode.Border,
        Parent = parent,
        theme = { Color = role or "border" },
    })
end

function UI.padding(parent, top, right, bottom, left)
    top = top or 0
    right = right or top
    bottom = bottom or top
    left = left or right
    return UI.new("UIPadding", {
        PaddingTop = UDim.new(0, top),
        PaddingRight = UDim.new(0, right),
        PaddingBottom = UDim.new(0, bottom),
        PaddingLeft = UDim.new(0, left),
        Parent = parent,
    })
end

function UI.list(parent, direction, spacing, alignment)
    return UI.new("UIListLayout", {
        FillDirection = direction or Enum.FillDirection.Vertical,
        Padding = UDim.new(0, spacing or 0),
        SortOrder = Enum.SortOrder.LayoutOrder,
        VerticalAlignment = alignment or Enum.VerticalAlignment.Top,
        Parent = parent,
    })
end

function UI.frame(props)
    props = props or {}
    if props.BackgroundTransparency == nil and props.theme == nil then
        props.BackgroundTransparency = 1
    end
    props.BorderSizePixel = props.BorderSizePixel or 0
    return UI.new("Frame", props)
end

function UI.label(props)
    props = props or {}
    props.BackgroundTransparency = props.BackgroundTransparency or 1
    props.BorderSizePixel = 0
    props.Font = props.Font or UI.FONT
    props.TextSize = props.TextSize or 14
    props.TextXAlignment = props.TextXAlignment or Enum.TextXAlignment.Left
    props.TextYAlignment = props.TextYAlignment or Enum.TextYAlignment.Center
    props.theme = props.theme or { TextColor3 = "text" }
    return UI.new("TextLabel", props)
end

-- Truncates with a middle ellipsis so both the start and the extension of long
-- instance names stay readable.
function UI.truncate(text, maxChars)
    if #text <= maxChars then
        return text
    end
    if maxChars <= 3 then
        return string.sub(text, 1, maxChars)
    end
    local head = math.ceil((maxChars - 3) / 2)
    local tail = maxChars - 3 - head
    return string.sub(text, 1, head) .. "..." .. string.sub(text, #text - tail + 1)
end

return UI

end
