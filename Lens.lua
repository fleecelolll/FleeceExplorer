function Widgets.colorPicker(startColor, onChanged, position)
    Widgets.closePopup()

    local hue, saturation, brightness = Color3.toHSV(startColor)

    local blocker = UI.new("TextButton", {
        Size = UDim2.fromScale(1, 1),
        BackgroundTransparency = 1,
        Text = "",
        AutoButtonColor = false,
        ZIndex = 600,
        Parent = Root.overlay,
    })
    activePopup = blocker

    local width, height = 210, 214
    local viewport = Root.gui.AbsoluteSize
    local x = Util.clamp(position.X, 4, math.max(4, viewport.X - width - 4))
    local y = Util.clamp(position.Y, 4, math.max(4, viewport.Y - height - 4))

