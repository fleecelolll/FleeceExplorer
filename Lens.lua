local function readValue(instance, name)
    local ok, value = pcall(function()
        return instance[name]
    end)
    if not ok then
        return nil, false
    end
    return value, true
end

local function buildRows()
    rows = {}

    if not target then
        return rows
    end

    if not ApiDump.ready then
        rows[1] = { kind = "message", text = ApiDump.loading and "Loading API dump..." or (ApiDump.error or "API dump unavailable") }
        return rows
    end

    local className = Util.safeClass(target)
    local descriptors = ApiDump.propertiesFor(className)

    local showHidden = Config.get("properties.showHidden", false)
    local showDeprecated = Config.get("properties.showDeprecated", false)
    local showReadOnly = Config.get("properties.showReadOnly", true)
    local grouped = Config.get("properties.groupByCategory", true)
    local needle = string.lower(filterText)

    local visible = {}
    for _, descriptor in ipairs(descriptors) do
        local keep = true
        if descriptor.hidden and not showHidden then
            keep = false
        elseif descriptor.deprecated and not showDeprecated then
            keep = false
        elseif descriptor.readOnly and not showReadOnly then
            keep = false
        elseif needle ~= "" and not string.find(string.lower(descriptor.name), needle, 1, true) then
            keep = false
        end

        if keep then
            -- A property the dump lists but this instance refuses to read is
            -- security-gated for us; drop it rather than showing an error row.
            local _, readable = readValue(target, descriptor.name)
            if readable then
                visible[#visible + 1] = descriptor
            end
        end
    end

    if grouped then
        local lastCategory = nil
        for _, descriptor in ipairs(visible) do
            if descriptor.category ~= lastCategory then
                lastCategory = descriptor.category
                rows[#rows + 1] = { kind = "header", text = descriptor.category }
            end
            rows[#rows + 1] = { kind = "property", descriptor = descriptor }
        end
    else
        local sorted = table.clone(visible)
        table.sort(sorted, function(a, b)
            return a.name < b.name
        end)
        for _, descriptor in ipairs(sorted) do
            rows[#rows + 1] = { kind = "property", descriptor = descriptor }
        end
    end

    -- Attributes are not in the API dump; append them as their own group.
    local attributesOk, attributes = pcall(function()
        return target:GetAttributes()
    end)
    if attributesOk and attributes then
        local names = {}
        for name in pairs(attributes) do
            if needle == "" or string.find(string.lower(name), needle, 1, true) then
                names[#names + 1] = name
            end
        end
        table.sort(names)
        if #names > 0 then
            rows[#rows + 1] = { kind = "header", text = "Attributes" }
            for _, name in ipairs(names) do
                rows[#rows + 1] = { kind = "attribute", name = name }
            end
        end
    end

    return rows
end

function Properties.rebuild()
    if not list then
        return
    end
    list:setItems(buildRows())

    if statusLabel then
        if target then
            statusLabel.Text = Util.safeClass(target)
        else
            statusLabel.Text = "no selection"
        end
    end
end

