function Properties.refreshRow(row)
    local entry = row.entry
    if not entry or not target then
        return
    end

    if entry.kind == "property" then
        local descriptor = entry.descriptor
        local value, ok = readValue(target, descriptor.name)
        if not ok then
            row.valueBox.Text = "<unreadable>"
            return
        end

        local text = Serialize.toText(value)

        if descriptor.typeName == "bool" or descriptor.typeCategory == "Enum"
            or descriptor.typeName == "Color3" or descriptor.typeName == "BrickColor" then
            row.valueButton.Text = (descriptor.typeName == "Color3" or descriptor.typeName == "BrickColor")
                and ("   " .. text) or text
            if descriptor.typeName == "Color3" then
                row.swatch.BackgroundColor3 = typeof(value) == "Color3" and value or Color3.new()
            elseif descriptor.typeName == "BrickColor" then
                row.swatch.BackgroundColor3 = typeof(value) == "BrickColor" and value.Color or Color3.new()
            end
        elseif editingDescriptor ~= descriptor then
            row.valueBox.Text = text
        end
    elseif entry.kind == "attribute" then
        local value = target:GetAttribute(entry.name)
        if editingDescriptor == nil then
            row.valueBox.Text = Serialize.toText(value)
        end
    end
end

local function bindRow(row, entry)
    row.entry = entry
    if not entry then
        return
    end

    row.header.Visible = false
    row.name.Visible = false
    row.valueBox.Visible = false
    row.valueButton.Visible = false
    row.swatch.Visible = false

    if entry.kind == "header" then
        row.header.Visible = true
        row.header.Text = string.upper(entry.text)
        row.frame.BackgroundColor3 = Theme.color("bg2")
        row.frame.BackgroundTransparency = 0
        return
    end

    if entry.kind == "message" then
        row.header.Visible = true
        row.header.Text = entry.text
        row.frame.BackgroundTransparency = 1
        return
    end

    row.frame.BackgroundTransparency = 1
    row.name.Visible = true

    if entry.kind == "attribute" then
        row.name.Text = entry.name
        row.name.TextColor3 = Theme.color("warning")
        row.valueBox.Visible = true
        row.valueBox.TextEditable = true
        row.valueBox.TextColor3 = Theme.color("text")
        Properties.refreshRow(row)
        return
    end

    local descriptor = entry.descriptor
    row.name.Text = descriptor.name
    row.name.TextColor3 = descriptor.readOnly and Theme.color("textDim") or Theme.color("text")

    local usesButton = descriptor.typeName == "bool"
        or descriptor.typeCategory == "Enum"
        or descriptor.typeName == "Color3"
        or descriptor.typeName == "BrickColor"

    if usesButton then
        row.valueButton.Visible = true
        row.valueButton.TextColor3 = descriptor.readOnly and Theme.color("textDim") or Theme.color("text")
        row.swatch.Visible = descriptor.typeName == "Color3" or descriptor.typeName == "BrickColor"
    else
        row.valueBox.Visible = true
        row.valueBox.TextEditable = not descriptor.readOnly
        row.valueBox.TextColor3 = descriptor.readOnly and Theme.color("textDim") or Theme.color("text")
    end

    Properties.refreshRow(row)
end

