local rawGethui = gethui
local rawCloneref = cloneref
local rawGetgenv = getgenv
local rawGetnilinstances = getnilinstances
local rawGetinstances = getinstances
local rawDecompile = decompile
local rawGetscriptbytecode = getscriptbytecode
