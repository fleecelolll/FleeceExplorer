__lensModules["ui/motion"] = function()
-- Tween helpers with one consistent set of easing curves.
--
-- Every animated surface goes through here so timings stay coherent, and so a
-- second tween on the same object cancels the first instead of fighting it.

local TweenService = game:GetService("TweenService")

local Motion = {}

Motion.FAST = 0.10
Motion.BASE = 0.16
Motion.SLOW = 0.28

local EASE = Enum.EasingStyle.Quart
local DIRECTION = Enum.EasingDirection.Out

local running = setmetatable({}, { __mode = "k" })

function Motion.tween(instance, properties, duration, style, direction)
    if typeof(instance) ~= "Instance" then
        return nil
    end

    local previous = running[instance]
    if previous then
        pcall(function()
            previous:Cancel()
        end)
    end

    local info = TweenInfo.new(
        duration or Motion.BASE,
        style or EASE,
        direction or DIRECTION
    )

    local ok, tween = pcall(function()
        return TweenService:Create(instance, info, properties)
    end)
    if not ok or not tween then
        -- A non-animatable property should still land.
        for property, value in pairs(properties) do
            pcall(function()
                instance[property] = value
            end)
        end
        return nil
    end

    running[instance] = tween
    tween:Play()
    return tween
end

-- Snappier curve for press feedback.
function Motion.press(instance, properties)
    return Motion.tween(instance, properties, Motion.FAST, Enum.EasingStyle.Sine)
end

function Motion.spring(instance, properties, duration)
    return Motion.tween(instance, properties, duration or Motion.SLOW, Enum.EasingStyle.Back)
end

-- Fades a container in from slightly below its resting position.
function Motion.enter(instance, targetPosition)
    local resting = targetPosition or instance.Position
    instance.Position = resting + UDim2.fromOffset(0, 8)
    instance.BackgroundTransparency = 1
    Motion.tween(instance, {
        Position = resting,
        BackgroundTransparency = 0,
    }, Motion.SLOW)
end

return Motion

end
