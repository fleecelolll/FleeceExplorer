local function applyFilter()
    filtered = {}
    local needle = string.lower(filterText)

    for _, entry in ipairs(entries) do
        if levels[entry.level] then
            if needle == "" or string.find(string.lower(entry.text), needle, 1, true) then
                filtered[#filtered + 1] = entry
            end
        end
    end

    if list then
        list:setItems(filtered)
        if autoScroll then
            list:scrollToIndex(#filtered, "nearest")
        end
    end
end

local function push(text, level)
    -- Multi-line messages become one entry per line so the fixed row height
    -- stays honest.
    for line in string.gmatch(tostring(text) .. "\n", "([^\n]*)\n") do
        entries[#entries + 1] = { text = line, level = level, clock = os.clock() }
    end

    if #entries > MAX_LINES then
        local excess = #entries - MAX_LINES
        for _ = 1, excess do
            table.remove(entries, 1)
        end
    end

    applyFilter()
end

