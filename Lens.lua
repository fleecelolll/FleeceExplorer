function ScriptView.open(scriptInstance)
    if not window then
        ScriptView.build()
    end

    currentScript = scriptInstance
    window:setTitle("Script - " .. Util.safeName(scriptInstance))
    window:setVisible(true)

    setSource("-- decompiling...")
    statusLabel.Text = "working"

    task.spawn(function()
        local providerId = PROVIDER_LABELS[providerDropdown.get()] or "native"
        local started = os.clock()
        local source, info = ScriptView.decompile(scriptInstance, providerId)
        local elapsed = math.floor((os.clock() - started) * 1000)

        if currentScript ~= scriptInstance then
            return
        end

        if not source then
            setSource("-- decompile failed:\n-- " .. tostring(info))
            statusLabel.Text = "failed"
            return
        end

        setSource(source)
        statusLabel.Text = string.format("%d lines · %s · %dms", #lines, tostring(info), elapsed)
    end)
end

