        Text = tostring(text),
        TextSize = 12,
        ZIndex = 951,
        Parent = frame,
    })
    UI.padding(frame, 0, 12, 0, 0)

    table.insert(active, 1, frame)
    while #active > MAX do
        local oldest = table.remove(active)
        pcall(function()
            oldest:Destroy()
        end)
    end
    reflow()

    frame.BackgroundTransparency = 1
    TweenService:Create(frame, TweenInfo.new(0.12), { BackgroundTransparency = 0 }):Play()

    task.delay(duration, function()
        for index, candidate in ipairs(active) do
            if candidate == frame then
                table.remove(active, index)
                break
            end
        end
        reflow()
        local fade = TweenService:Create(frame, TweenInfo.new(0.15), { BackgroundTransparency = 1 })
        fade:Play()
        fade.Completed:Wait()
        pcall(function()
            frame:Destroy()
        end)
    end)

    return frame
end

return Toast

