-- roleOrValue may be a role name, or a literal Color3/number for the rare
-- object that should not follow the theme.
function Theme.register(instance, property, roleOrValue, modifier)
    if typeof(instance) ~= "Instance" then
        return instance
    end
    registryCount = registryCount + 1
    registry[registryCount] = {
        instance = instance,
        property = property,
        role = roleOrValue,
        modifier = modifier,
    }
    Theme.applyEntry(registry[registryCount])
    return instance
end

function Theme.applyEntry(entry)
    local instance = entry.instance
    if typeof(instance) ~= "Instance" then
        return false
    end

    local value
    if typeof(entry.role) == "Color3" or type(entry.role) == "number" then
        value = entry.role
    elseif type(entry.role) == "string" then
        if string.sub(entry.role, 1, 6) == "trans:" then
            value = Theme.transparency(string.sub(entry.role, 7))
        else
            value = Theme.color(entry.role)
        end
    end

    if value == nil then
        return true
    end

    if entry.modifier then
        value = entry.modifier(value)
    end

    local ok = pcall(function()
        instance[entry.property] = value
    end)
    return ok
end

-- Sweeps the registry, applying every entry and compacting away dead objects.
function Theme.apply()
    local live = {}
    local liveCount = 0
    for index = 1, registryCount do
        local entry = registry[index]
        if entry then
            local alive = pcall(function()
                return entry.instance.Parent
            end)
            if alive and Theme.applyEntry(entry) then
                liveCount = liveCount + 1
                live[liveCount] = entry
            end
        end
    end
    registry = live
    registryCount = liveCount
    Theme.changed:fire(current)
end

