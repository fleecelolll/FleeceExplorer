    for index, toast in ipairs(active) do
        toast.Position = UDim2.new(0.5, 0, 1, -40 - (index - 1) * 30)
    end
end

function Toast.show(text, duration)
    duration = duration or 2.2

    if not Root.gui then
        return
    end

    local frame = UI.frame({
        Size = UDim2.fromOffset(10, 26),
        AnchorPoint = Vector2.new(0.5, 1),
