function Widgets.slider(props)
    local minimum = props.min or 0
    local maximum = props.max or 1
    local step = props.step or 0.01
    local value = Util.clamp(props.value or minimum, minimum, maximum)

    local holder = UI.frame({
        Size = props.Size or UDim2.new(1, 0, 0, 34),
        LayoutOrder = props.LayoutOrder,
        BackgroundTransparency = 1,
        Parent = props.Parent,
    })

    local caption = UI.label({
        Size = UDim2.new(1, -50, 0, 14),
        Text = props.Text or "",
        TextSize = 12,
        Parent = holder,
        theme = { TextColor3 = "textDim" },
    })

    local readout = UI.label({
        Size = UDim2.new(0, 50, 0, 14),
        Position = UDim2.new(1, -50, 0, 0),
        Text = Util.formatNumber(value),
        TextSize = 12,
        TextXAlignment = Enum.TextXAlignment.Right,
        Parent = holder,
        theme = { TextColor3 = "textDim" },
    })

    local track = UI.frame({
        Size = UDim2.new(1, 0, 0, 5),
        Position = UDim2.new(0, 0, 0, 22),
        Parent = holder,
        theme = { BackgroundColor3 = "bg2" },
    })
    UI.corner(track, 3)

    local fill = UI.frame({
        Size = UDim2.fromScale((value - minimum) / math.max(maximum - minimum, 1e-6), 1),
        Parent = track,
        theme = { BackgroundColor3 = "accent" },
    })
    UI.corner(fill, 3)

    local knob = UI.frame({
        Size = UDim2.fromOffset(11, 11),
        AnchorPoint = Vector2.new(0.5, 0.5),
        Position = UDim2.new((value - minimum) / math.max(maximum - minimum, 1e-6), 0, 0.5, 0),
        ZIndex = 3,
        Parent = track,
        theme = { BackgroundColor3 = "accent" },
    })
    UI.corner(knob, 6)

    local hit = UI.new("TextButton", {
        Size = UDim2.new(1, 0, 0, 20),
        Position = UDim2.new(0, 0, 0, 15),
        BackgroundTransparency = 1,
        Text = "",
        AutoButtonColor = false,
        Parent = holder,
    })

    local function applyFromX(x)
        local absoluteX = track.AbsolutePosition.X
        local width = math.max(track.AbsoluteSize.X, 1)
        local alpha = Util.clamp((x - absoluteX) / width, 0, 1)
        local raw = minimum + alpha * (maximum - minimum)
        local snapped = minimum + math.floor((raw - minimum) / step + 0.5) * step
        snapped = Util.clamp(snapped, minimum, maximum)

        if snapped == value then
            return
        end
        value = snapped

        local ratio = (value - minimum) / math.max(maximum - minimum, 1e-6)
        fill.Size = UDim2.fromScale(ratio, 1)
        knob.Position = UDim2.new(ratio, 0, 0.5, 0)
        readout.Text = Util.formatNumber(Util.round(value, 3))

        if props.onChanged then
            props.onChanged(value)
        end
    end

    local dragging = false
    hit.InputBegan:Connect(function(input)
        if input.UserInputType == Enum.UserInputType.MouseButton1 or input.UserInputType == Enum.UserInputType.Touch then
            dragging = true
            applyFromX(input.Position.X)
        end
    end)
    UserInputService.InputChanged:Connect(function(input)
        if dragging and (input.UserInputType == Enum.UserInputType.MouseMovement or input.UserInputType == Enum.UserInputType.Touch) then
            applyFromX(input.Position.X)
        end
    end)
    UserInputService.InputEnded:Connect(function(input)
        if input.UserInputType == Enum.UserInputType.MouseButton1 or input.UserInputType == Enum.UserInputType.Touch then
            dragging = false
        end
    end)

    return {
        instance = holder,
        caption = caption,
        get = function()
            return value
        end,
        set = function(newValue)
            value = Util.clamp(newValue, minimum, maximum)
            local ratio = (value - minimum) / math.max(maximum - minimum, 1e-6)
            fill.Size = UDim2.fromScale(ratio, 1)
            knob.Position = UDim2.new(ratio, 0, 0.5, 0)
            readout.Text = Util.formatNumber(Util.round(value, 3))
        end,
    }
end

