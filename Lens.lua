local function bindRow(row, node)
    row.node = node
    row.hovered = false
    if not node then
        return
    end

    local indent = node.depth * INDENT
    local showIcons = Config.get("ui.showClassIcons", true)

    row.arrow.Position = UDim2.new(0, indent + 2, 0.5, -7)
    row.icon.Position = UDim2.new(0, indent + 18, 0.5, -8)
    row.icon.Visible = showIcons

    local textLeft = indent + (showIcons and 36 or 20)
    row.name.Position = UDim2.new(0, textLeft, 0, 0)

    if node.virtual then
        setChevron(row, true, Tree.isExpanded(node.descriptor), true)
        Icons.apply(row.icon, "Folder")
        row.name.Size = UDim2.new(1, -textLeft - 60, 1, 0)
        row.name.Text = node.descriptor.label
        row.name.Font = UI.FONT_BOLD
        row.name.TextColor3 = Theme.color("text")

        local hint = node.descriptor.hint
        if type(hint) == "function" then
            local ok, value = pcall(hint)
            hint = ok and value or ""
        end
        row.class.Visible = true
        row.class.Text = hint or ""
        row.marker.Size = UDim2.new(0, 0, 0.62, 0)
        row.frame.BackgroundTransparency = 1
        return
    end

    local instance = node.instance
    setChevron(row, node.expandable, Tree.isExpanded(instance), true)

    if showIcons then
        Icons.apply(row.icon, Util.safeClass(instance))
    end

    -- Services read as section headers; their children are lighter and
    -- smaller, which is what gives the tree a sense of depth.
    local isGroup = node.depth == 0
    row.name.Font = isGroup and UI.FONT_BOLD or UI.FONT
    row.name.TextSize = isGroup and 13 or 12

    -- The class column only earns its space on a wide rail; below that the
    -- name matters more and ClassName is a row away in Properties.
    local showClass = row.frame.AbsoluteSize.X >= 340
    row.class.Visible = showClass
    row.name.Size = UDim2.new(1, -textLeft - (showClass and 118 or 12), 1, 0)

    local name = Util.safeName(instance)
    row.name.Text = node.removed and (name .. "  (removed)") or name
    if showClass then
        row.class.Text = Util.safeClass(instance)
    end

    Explorer.paintRow(row, true)
end

