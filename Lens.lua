function Widgets.dropdown(props)
    local options = props.options or {}
    local value = props.value or options[1]

    local button = UI.new("TextButton", {
        Size = props.Size or UDim2.new(1, 0, 0, 24),
        Position = props.Position,
        LayoutOrder = props.LayoutOrder,
        Text = "",
        AutoButtonColor = false,
        BorderSizePixel = 0,
        ZIndex = props.ZIndex or 1,
        Parent = props.Parent,
        theme = { BackgroundColor3 = "bg2" },
    })
    UI.corner(button, 4)
    UI.stroke(button, "border", 1)

    local label = UI.label({
        Size = UDim2.new(1, -28, 1, 0),
        Position = UDim2.fromOffset(8, 0),
        Text = tostring(value or ""),
        TextSize = 13,
        ZIndex = (props.ZIndex or 1) + 1,
        Parent = button,
    })

    UI.label({
        Size = UDim2.fromOffset(16, 16),
        Position = UDim2.new(1, -20, 0.5, -8),
        Text = "▾",
        TextSize = 11,
        TextXAlignment = Enum.TextXAlignment.Center,
        ZIndex = (props.ZIndex or 1) + 1,
        Parent = button,
        theme = { TextColor3 = "textDim" },
    })

    local api = {}

    function api.set(newValue, silent)
        value = newValue
        label.Text = tostring(newValue or "")
        if not silent and props.onChanged then
            props.onChanged(newValue)
        end
    end

    function api.get()
        return value
    end

    function api.setOptions(newOptions)
        options = newOptions or {}
    end

    button.MouseButton1Click:Connect(function()
        local entries = {}
        for _, option in ipairs(options) do
            entries[#entries + 1] = {
                text = tostring(option),
                hint = option == value and "•" or nil,
                onClick = function()
                    api.set(option)
                end,
            }
        end
        local absolutePosition = button.AbsolutePosition
        Widgets.popup(entries, Vector2.new(absolutePosition.X, absolutePosition.Y + button.AbsoluteSize.Y + 2), {
            width = math.max(button.AbsoluteSize.X, 120),
        })
    end)

    api.instance = button
    return api
end

