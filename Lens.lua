local function applyValue(descriptor, text)
    if not target then
        return
    end

    local current = readValue(target, descriptor.name)
    local value, err

    if descriptor.typeCategory == "Enum" then
        value, err = Serialize.parseEnum(descriptor.typeName, text)
    else
        value, err = Serialize.parse(text, descriptor.typeName, current)
    end

    if value == nil then
        Toast.show(descriptor.name .. ": " .. tostring(err or "could not parse"))
        return false
    end

    local ok, writeErr = pcall(function()
        target[descriptor.name] = value
    end)
    if not ok then
        Toast.show(descriptor.name .. ": " .. tostring(writeErr))
        return false
    end
    return true
end

